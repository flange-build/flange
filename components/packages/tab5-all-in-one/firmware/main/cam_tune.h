#pragma once
/*
 * 摄像头画质调校：**所有可调参数集中在本文件**，控制律是纯逻辑、不依赖 ESP-IDF，
 * 宿主机可编译可测试（test/test_cam_tune.c）。
 *
 * 存在的理由是两个实机问题：
 *   ① 整体发绿 —— **白平衡缺失**，见下面「为什么是白平衡不是 bayer order」。
 *   ② 曝光不对 —— 传感器固定用模式表里的 exp_def/gain_def，换个光照就欠曝或过曝。
 *
 * 硬件能给什么、不能给什么（本板 ESP32-P4 **rev v1.0**，逐个模块查过版本门）：
 *   esp_driver_isp/src/isp_wbg.c:30   白平衡增益  ESP_CHIP_REV_ABOVE(rev,300) ⇒ **用不了**
 *   esp_driver_isp/src/isp_blc.c:30   黑电平校正  同上 ⇒ 用不了
 *   esp_driver_isp/src/isp_ccm.c      颜色校正矩阵 **无版本门** ⇒ 可用，这就是替代路子
 *   esp_driver_isp/src/isp_lsc.c:58   镜头阴影    ESP_CHIP_REV_ABOVE(rev,100)，而
 *                                     该宏是 `(min_rev) <= (rev)`（soc/chip_revision.h:31），
 *                                     rev v1.0 ⇒ 100 <= 100 为**真**，可用（本工程没用）
 * ⇒ 硬件 WBG 不可用，**白平衡靠 CCM 的对角线做**：CCM 在去马赛克之后的 RGB 域上
 *   乘一个 3×3 矩阵，对角阵 diag(kr, 1, kb) 与 WBG 的通道增益在数学上等价。
 *   rev < 3.0 的 CCM 定点格式是「2 位整数 + 10 位小数 + 符号」
 *   （hal/isp_ll.h:138-144 的 #if HAL_CONFIG(CHIP_SUPPORT_MIN_REV) >= 300 分支），
 *   ⇒ **系数上限是 4.0**，esp_isp_ccm_configure() 超范围直接返回 ESP_ERR_INVALID_ARG。
 *
 * ══ 为什么断定「发绿 = 白平衡」而不是「bayer order 配错」════════════════════
 *
 * 三条独立的依据，任何一条单独成立都够：
 *
 *  1. **物理必然。** Bayer 阵列 50% 是绿色像素，绿滤光片的透过率本身也最高，
 *     而本管线里 RAW→RGB 只有 ISP 的去马赛克一步（camera_csi.c 的 isp_cfg），
 *     **没有任何一处对三个通道施加不同的增益** —— WBG 用不了、CCM 在本次改动前
 *     压根没配。裸 Bayer 数据不做白平衡必然偏绿，这不是「可能」，是管线的定义。
 *
 *  2. **bayer order 错的症状不是这个。** 四种 order 的差别是 2×2 单元里 R 与 B
 *     的位置，而 G 在四种 order 里都占对角线两格 —— 所以配错 order 时绿通道拿到的
 *     仍然大体是绿，表现为**红蓝对调**（拍红色物体出蓝色）外加去马赛克插值方向错
 *     导致的**棋盘格高频伪影**，而不是整幅均匀偏绿。
 *
 *  3. **可证伪的现场判据**（烧板后按这个判，别只信推理）：
 *     看自检行「通道均值 R.. G.. B..」——
 *       R < G > B 且比例大体固定、与镜头对着什么无关  ⇒ 白平衡，本文件的 CCM 治它；
 *       拍**红色**物体时 b_mean 反而比 r_mean 高       ⇒ 红蓝对调，那才轮到去改
 *                                                       camera_csi.c 的 bayer_order
 *                                                       （BGGR ↔ RGGB 恰好互换 R/B）。
 */
#include <stdint.h>
#include <stdbool.h>

/* ══════════════════════════════════════════════════════════════════════
 *  可调参数（**只在这里改**）
 * ══════════════════════════════════════════════════════════════════════ */

/*
 * ── 白平衡：CCM 对角线增益，单位 1/1000 ──────────────────────────────
 *
 * 施加到 ISP 的矩阵是 diag(R, G, B)/1000，绿固定 1.000 作基准，红蓝往上抬
 * （而不是把绿压下去）：抬红蓝时绿通道保持满量程，压绿则要靠 AE 多加一档增益
 * 才能补回亮度，白白多一份噪声。上限 4.0 是硬件定点格式给的，见文件头。
 *
 * ⚠️ **默认值是估计值，不是实测值。** 它只是个比「什么都不做」好得多的起点：
 *    典型 CMOS 传感器（带 IR-cut）在室内白光下，绿通道大约是红的 1.5~2 倍、
 *    蓝的 1.4~1.8 倍。真正的数必须**量出来**，一次开机就能定死：
 *
 *      1. 烧板，让摄像头对着一张**白纸**（或灰卡），照明用日常那盏灯，充满画面；
 *      2. 等 AE 收敛（自检行「AE ... 收敛」且亮度均值落在目标附近 —— 曝光没稳时
 *         通道均值也没意义）；
 *      3. 读 camera 的自检行：
 *            [自检] 画质 CCM=... R×1.700 G×1.000 B×1.550
 *                   | 通道均值 R98 G121 B105 → 建议 CCM R×2.099 B×1.786
 *         最后那两个数已经把「当前生效的 CCM」算进去了（是**绝对**建议值，
 *         不是增量），直接抄进下面两行重新编译即可；
 *      4. 再跑一次，通道均值应当三个数相近（差 <5%），建议值应当≈当前值。
 *
 * ⓘ 只做对角线、不做非对角项：非对角项管的是色彩还原准确度（把传感器的光谱响应
 *   映射到 sRGB），需要色卡与拟合，与「发绿」这个问题无关，刻意不做。
 */
#define CAM_CCM_GAIN_R_MILLI   1700
#define CAM_CCM_GAIN_G_MILLI   1000
#define CAM_CCM_GAIN_B_MILLI   1550

/*
 * ── 自动曝光 ────────────────────────────────────────────────────────
 *
 * 目标亮度：BT.601 亮度均值的期望值。120 是 8 位量程的中位偏上一点 ——
 * 取太高（>150）会让室内白墙这类大面积亮场把高光推到削顶，取太低则整体发灰。
 */
#define CAM_AE_TARGET          120

/*
 * 死区：|均值 − 目标| ≤ 这个数就完全不动。**防振荡的第一道闸**。
 * 12 ≈ 目标的 10%，小于这个差别肉眼基本看不出，却足以让量化噪声与画面里
 * 一片云飘过就触发一次曝光调整 —— 那正是「画面一亮一暗地喘」的来源。
 */
#define CAM_AE_DEADBAND        12

/*
 * 阻尼：每次只走到「理论正确值」的 NUM/DEN。**防振荡的第二道闸**。
 * 取 1/2 的理由：测量到执行之间有约 170 ms 的滞后（推导见 CAM_AE_INTERVAL_TICKS），
 * 一个带滞后的比例环节，增益 1.0 就在振荡边缘，0.5 留一倍余量，代价只是多花
 * 一两拍收敛。**不要**改成 1/1「让它快点」。
 */
#define CAM_AE_DAMP_NUM        1
#define CAM_AE_DAMP_DEN        2

/*
 * 单步限幅：一次最多把曝光量放大/缩小这个倍数。**防振荡的第三道闸**。
 * 场景骤变（盖住镜头 ⇒ 均值 2）时理论倍数会到 60×，一步跳过去必然大幅过冲、
 * 然后反向再来一次，正是最难看的那种喘。限成 2× 后最坏情况约 6 步（≈2 秒）
 * 走完 60×，全程单调、不过冲。
 */
#define CAM_AE_STEP_MAX        2

/*
 * 增益上限，单位 1/1000。传感器自己的表能到 63×（噪声已经盖过画面），
 * 这里按「还看得出是画面」压到 16×。**欠曝时先加曝光时间再加增益**，
 * 所以这个上限只在很暗的场景才起作用。
 * 下限恒为增益表第 0 档（1.000×），不单设常量：低于 1× 传感器表里就没有。
 */
#define CAM_AE_GAIN_MAX_MILLI  16000

/*
 * 更新频率限制：每这么多拍才允许动一次曝光。**防振荡的第四道闸**。
 * 一拍 = UVC 帧泵的一帧 = 100 ms（10 fps），所以 3 拍 = 300 ms。
 *
 * 这个数由**测量滞后**定，不能凭感觉调小：
 *   传感器把新曝光值应用到下一帧          ≈ 1~2 帧 @30fps =  33~66 ms
 *   CSI 侧最多积压 2 帧才轮到我们取走      ≈           至多  66 ms
 *   帧泵自己 100 ms 一拍                    ≈           至多 100 ms
 *   合计最坏 ≈ 230 ms ⇒ 取 300 ms，保证**每次测量都反映的是上一次下发的结果**。
 * 调小到 1 拍的话，前两次测量还是旧曝光下的画面，控制器会以为「没效果」而继续
 * 加码 —— 这是曝光振荡最经典的成因，比例增益再小也救不回来。
 */
#define CAM_AE_INTERVAL_TICKS  3

/* 连续这么多次落在死区内就报「收敛」。纯观测量，不参与控制。 */
#define CAM_AE_CONVERGE_TICKS  3

/* ══════════════════════════════════════════════════════════════════════
 *  自动曝光：数据结构与控制律
 * ══════════════════════════════════════════════════════════════════════ */

/*
 * 传感器给出的可调范围。全部**运行时向 esp_cam_sensor 查**（query_para_desc），
 * 不写死：曝光上限跟着 VTS 走，增益表长度跟着 menuconfig 的
 * CONFIG_CAMERA_SC202CS_ABSOLUTE_GAIN_LIMIT 与增益优先策略走，抄成常量必然过期。
 */
typedef struct {
    uint32_t exp_min;          /* 曝光寄存器值下限 */
    uint32_t exp_max;          /* 上限 */
    const uint32_t *gain_map;  /* 绝对增益表（单调升，单位 1/1000），传感器组件持有 */
    uint32_t gain_count;       /* 表长；**合法下标只到 gain_count − 1**，见下面 ⚠️ */
} cam_ae_limits_t;

/*
 * AE 状态机。曝光与增益两个旋钮被合成一个标量 **ev（曝光量）**：
 *     ev = 曝光寄存器值 × 绝对增益 ÷ 1000
 * 亮度与 ev 成正比（在不削顶的范围内），所以控制律只需要对这一个数做比例控制，
 * 「先用曝光时间、不够再加增益」的分配策略被隔离在 cam_ae_split() 里 ——
 * 控制与分配分开，两件事各自可测。
 */
typedef struct {
    uint32_t ev;          /* 当前曝光量（**量化后的实际值**，不是请求值，见 cam_ae_step） */
    uint32_t exposure;    /* 已下发的曝光寄存器值 */
    uint32_t gain_index;  /* 已下发的增益档位下标 */
    uint32_t settle;      /* 还要跳过几拍才允许再动（更新频率限制） */
    uint32_t in_band;     /* 连续落在死区内的次数，到 CAM_AE_CONVERGE_TICKS 封顶 */
    uint32_t updates;     /* 累计真正下发过多少次，自检行用 */
    uint8_t  last_mean;   /* 最近一次看到的亮度均值，自检行用 */
} cam_ae_state_t;

/* 曝光量 = 曝光寄存器值 × 绝对增益(1/1000)。溢出安全：1244 × 63008 仍在 uint32 内。 */
uint32_t cam_ae_ev(uint32_t exposure, uint32_t gain_milli);

/*
 * 把一个曝光量拆成 (曝光寄存器值, 增益档位)。
 *
 * 策略：**曝光时间优先，增益垫底** —— 曝光时间不增加噪声，模拟/数字增益都增加。
 * 只有当曝光顶到 exp_max 还不够亮时才开始往上翻增益档。
 * 增益档取「不超过所需值的最大一档」（表单调升），并同时受 CAM_AE_GAIN_MAX_MILLI 约束。
 *
 * ⚠️ 下标严格落在 [0, gain_count − 1]。**不能指望传感器驱动兜底**：
 *    sc202cs.c:1167 的 `MIN(u32_val, s_limited_abs_gain_index)` 是个 off-by-one ——
 *    当增益表里没有任何一项超过 CONFIG_CAMERA_SC202CS_ABSOLUTE_GAIN_LIMIT 时
 *    （默认恰好如此：表的最大值 63008 == 上限 63008，:1526-1532 那个循环从不 break），
 *    s_limited_abs_gain_index 停在 ARRAY_SIZE 上，于是下标 == 表长也被放行，
 *    sc202cs_gain_map[表长] 是一次**越界读**。传进去的数必须自己保证合法。
 *
 * ev 为 0 或 limits 非法时输出下限档，不会除零。
 */
void cam_ae_split(uint32_t ev, const cam_ae_limits_t *lim,
                  uint32_t *exposure, uint32_t *gain_index);

/* 用传感器的默认曝光/增益初始化状态机（它们此刻就是芯片里的实际值）。 */
void cam_ae_init(cam_ae_state_t *st, const cam_ae_limits_t *lim,
                 uint32_t exposure, uint32_t gain_index);

/*
 * 走一拍。**每帧都要调**（频率限制在函数内部做，不由调用方判断）。
 *
 * 返回 true 表示 st->exposure / st->gain_index 变了、需要下发给传感器；
 * 返回 false 表示这一拍不动（没到更新周期 / 落在死区 / 已经顶到上下限 /
 * 量化后落回同一档）—— 调用方**不要**在 false 时下发，那等于把 I2C 事务
 * 白白撒在总线上（这条总线还挂着 20 ms 轮询的触摸）。
 *
 * 四道防振荡闸的位置见上面各常量的注释。除此之外还有一条：state 里存的 ev 是
 * **量化后的实际曝光量**而不是请求值，否则每次请求与实际的那点差额会在下一拍
 * 被当成新的误差再放大一次，形成慢速极限环。
 */
bool cam_ae_step(cam_ae_state_t *st, uint8_t lum_mean, const cam_ae_limits_t *lim);

/* 是否已收敛（连续 CAM_AE_CONVERGE_TICKS 次落在死区内）。 */
bool cam_ae_converged(const cam_ae_state_t *st);

/* ══════════════════════════════════════════════════════════════════════
 *  白平衡：从实测通道均值反推 CCM 系数
 * ══════════════════════════════════════════════════════════════════════ */

/*
 * 由「当前生效的 CCM 增益」+「当前画面的分通道均值」算出**绝对**的建议增益。
 *
 *     建议 = 当前 × g_mean / 该通道均值
 *
 * 之所以要乘上当前值：均值是**施加 CCM 之后**测到的，直接拿 g/r 当增益就把
 * 已经生效的那一份又算了一遍，越调越偏。乘进去之后这个式子是**幂等**的 ——
 * 系数正确时三个均值相等，建议值恰好等于当前值，不会来回摆。
 *
 * 只在镜头对着白/灰面时有意义（灰世界假设）。红通道均值为 0（全黑/纯蓝画面）时
 * 该通道保持当前值不变，不会除零、也不会给出一个荒唐的建议。
 * 输出限幅到 [250, 4000]：上限是硬件定点格式的 4.0，下限防止一次误测把系数打到 0。
 */
void cam_awb_suggest(uint8_t r_mean, uint8_t g_mean, uint8_t b_mean,
                     uint32_t cur_r_milli, uint32_t cur_b_milli,
                     uint32_t *sug_r_milli, uint32_t *sug_b_milli);
