/*
 * ── 白平衡：CCM 对角线增益的**开机初值**，单位 1/1000 ────────────────
 *
 * 施加到 ISP 的矩阵是 diag(R, G, B)/1000，绿固定 1.000 作基准，红蓝往上抬
 * （而不是把绿压下去）：抬红蓝时绿通道保持满量程，压绿则要靠 AE 多加一档增益
 * 才能补回亮度，白白多一份噪声。上限 4.0 是硬件定点格式给的，见文件头。
 *
 * ⓘ **这三个数现在只是初值。** 闭环 AWB（下一节）开机后会从这里出发、
 *   按画面实测的通道均值把 R/B 调到位。它们仍然重要：
 *     · 开机最初一两秒 AWB 还没收敛，画面颜色由它们决定 —— 从一个大体对的
 *       地方出发，比从 1.000 出发少几拍、也不会让用户看到一段乱跳的颜色；
 *     · CAM_AWB_ENABLE = 0（钉回纯静态）时它们就是最终值；
 *     · 场景一直不可信（单色/太暗）时 AWB 一步都不走，画面停在它们身上。
 *
 * ⚠️ 默认值是估计值，不是实测值。想把它们量准（或者要退回纯静态档）时：
 *
 *      1. 烧板，让摄像头对着一张**白纸**（或灰卡），照明用日常那盏灯，充满画面；
 *      2. 等 AE 收敛（自检行「AE ... 收敛」且亮度均值落在目标附近 —— 曝光没稳时
 *         通道均值也没意义）；
 *      3. 读 camera 的自检行：
 *            [自检] 画质 CCM=... 当前 R×1.700 G×1.000 B×1.550
 *                   | 通道均值 R98 G121 B105 → 建议 CCM R×2.099 B×1.786
 *         最后那两个数已经把「当前生效的 CCM」算进去了（是**绝对**建议值，
 *         不是增量），直接抄进下面两行重新编译即可；
 *      4. 再跑一次，通道均值应当三个数相近（差 <5%），建议值应当≈当前值。
 *
 *    ⓘ AWB 开着的时候这一步会**自动**发生：自检行里的「当前」就是 AWB 调出来的
 *      值，抄它就等于把闭环的结论固化成静态标定。
 *
 * ⓘ 只做对角线、不做非对角项：非对角项管的是色彩还原准确度（把传感器的光谱响应
 *   映射到 sRGB），需要色卡与拟合，与「发绿」这个问题无关，刻意不做。
 */
#define CAM_CCM_GAIN_R_MILLI   1700
#define CAM_CCM_GAIN_G_MILLI   1000
#define CAM_CCM_GAIN_B_MILLI   1550

/*
 * ── 自动曝光 ────────────────────────────────────────────────────────
 *
 * 目标亮度：BT.601 亮度均值的期望值。120 是 8 位量程的中位偏上一点 ——
 * 取太高（>150）会让室内白墙这类大面积亮场把高光推到削顶，取太低则整体发灰。
 */
#define CAM_AE_TARGET          120

/*
 * 死区：|均值 − 目标| ≤ 这个数就完全不动。**防振荡的第一道闸**。
 * 12 ≈ 目标的 10%，小于这个差别肉眼基本看不出，却足以让量化噪声与画面里
 * 一片云飘过就触发一次曝光调整 —— 那正是「画面一亮一暗地喘」的来源。
 */
#define CAM_AE_DEADBAND        12

/*
 * 阻尼：每次只走到「理论正确值」的 NUM/DEN。**防振荡的第二道闸**。
 * 取 1/2 的理由：测量到执行之间有约 170 ms 的滞后（推导见 CAM_AE_INTERVAL_TICKS），
 * 一个带滞后的比例环节，增益 1.0 就在振荡边缘，0.5 留一倍余量，代价只是多花
 * 一两拍收敛。**不要**改成 1/1「让它快点」。
 */
#define CAM_AE_DAMP_NUM        1
#define CAM_AE_DAMP_DEN        2

/*
 * 单步限幅：一次最多把曝光量放大/缩小这个倍数。**防振荡的第三道闸**。
 * 场景骤变（盖住镜头 ⇒ 均值 2）时理论倍数会到 60×，一步跳过去必然大幅过冲、
 * 然后反向再来一次，正是最难看的那种喘。限成 2× 后最坏情况约 6 步（≈2 秒）
 * 走完 60×，全程单调、不过冲。
 */
#define CAM_AE_STEP_MAX        2

/*
 * 增益上限，单位 1/1000。传感器自己的表能到 63×（噪声已经盖过画面），
 * 这里按「还看得出是画面」压到 16×。**欠曝时先加曝光时间再加增益**，
 * 所以这个上限只在很暗的场景才起作用。
 * 下限恒为增益表第 0 档（1.000×），不单设常量：低于 1× 传感器表里就没有。
 */
#define CAM_AE_GAIN_MAX_MILLI  16000

/*
 * 更新频率限制：每这么多拍才允许动一次曝光。**防振荡的第四道闸**。
 * 一拍 = UVC 帧泵的一帧 = 100 ms（10 fps），所以 3 拍 = 300 ms。
 *
 * 这个数由**测量滞后**定，不能凭感觉调小：
 *   传感器把新曝光值应用到下一帧          ≈ 1~2 帧 @30fps =  33~66 ms
 *   CSI 侧最多积压 2 帧才轮到我们取走      ≈           至多  66 ms
 *   帧泵自己 100 ms 一拍                    ≈           至多 100 ms
 *   合计最坏 ≈ 230 ms ⇒ 取 300 ms，保证**每次测量都反映的是上一次下发的结果**。
 * 调小到 1 拍的话，前两次测量还是旧曝光下的画面，控制器会以为「没效果」而继续
 * 加码 —— 这是曝光振荡最经典的成因，比例增益再小也救不回来。
 */
#define CAM_AE_INTERVAL_TICKS  3

/* 连续这么多次落在死区内就报「收敛」。纯观测量，不参与控制。 */
#define CAM_AE_CONVERGE_TICKS  3

/*
 * ── 自动白平衡（闭环，灰世界假设）──────────────────────────────────
 *
 * 总开关。**默认开**。设成 0 就钉回纯静态标定（CCM 开机配一次、之后一动不动，
 * 也就是这一改动之前那个已经实机验证过的状态）—— AWB 出任何问题时的退路，
 * 一行改动、不必回滚代码。设成 0 时 cam_awb_step() 相关的代码在 camera_csi.c
 * 里整段不编译，运行期开销为零。
 */
#define CAM_AWB_ENABLE         1

/*
 * 更新周期，单位「拍」（一拍 = UVC 帧泵一帧 = 100 ms）。10 拍 = 1 秒。
 *
 * 为什么比 AE 的 3 拍慢一大截 —— 这是**与 AE 解耦的第二条措施**（第一条是
 * 归一化，见 cam_awb_step 的说明）：两个闭环吃同一份统计量，AWB 改 CCM 会把
 * 画面整体抬亮、AE 会把它看成扰动。控制上处理这种耦合的标准手段是**时间尺度
 * 分离** —— 让慢环（AWB）的周期远大于快环（AE）的整定时间，慢环每次看到的
 * 就是快环的稳态，而不是它的暂态。AE 从最坏情况收敛约 6 步 × 300 ms ≈ 2 秒，
 * 加上 AWB 还要等 AE 报收敛才动（第三条措施），1 秒的周期已经足够。
 * 调大 = 更稳更慢；调小到 AE 周期附近 = 两个环互相追着跑，颜色与亮度一起喘。
 */
#define CAM_AWB_INTERVAL_TICKS 10

/*
 * 死区：建议增益与当前增益相差不到这个百分比就完全不动。
 * 5% 的增益差在画面上基本看不出（≈ 半个 JND），却足以让统计噪声每秒重配一次
 * CCM —— 那是 9 个寄存器的写，还会让「已收敛」这个观测量永远为假。
 */
#define CAM_AWB_DEADBAND_PCT   5

/*
 * 阻尼：每次只走到建议值的 NUM/DEN。理由与 AE 那一处同源 ——
 * 从「改 CCM」到「测到反映它的那一帧」同样有 100~200 ms 的滞后，
 * 带滞后的比例环节增益 1.0 就在振荡边缘。代价只是多花一两个周期收敛。
 */
#define CAM_AWB_DAMP_NUM       1
#define CAM_AWB_DAMP_DEN       2

/*
 * 单步限幅：一个周期内增益最多变这个百分比。
 * 25% 的意思是最坏情况下从 1.000 走到 3.000 要 5 个周期（5 秒）—— 慢，但
 * **单调、不过冲**。白平衡的过冲比曝光的过冲更难看：颜色反向偏一下，人眼对
 * 色偏的敏感度远高于对亮度的。
 */
#define CAM_AWB_STEP_MAX_PCT   25

/*
 * ══ 灰世界失效的四道防护 ══
 *
 * 灰世界假设说的是「一幅普通画面里所有颜色的平均是灰的」。它对**混杂场景**
 * 大体成立，对**单色场景**则完全不成立 —— 镜头怼着一堵红墙时，灰世界会认定
 * 红通道太强、把红压下去，结果红墙变成灰墙、画面其余部分泛青。这是闭环 AWB
 * 的头号通病，必须挡住。四道判据各挡一类，且**每一道都能在自检行里单独看到
 * 计数**，出问题时分得清是被哪一条挡的。
 *
 * ① 亮度下限：画面太暗时通道均值由**读出噪声**主导（暗处信噪比 <1），
 *   比值纯属随机。40 ≈ AE 目标 120 的三分之一 —— 低到这个程度说明 AE 已经
 *   顶到限位还不够亮，此时的颜色信息不可信。
 * ② 亮度上限：大面积接近削顶时通道均值被 255 **截断**，比值同样失真
 *   （原本 300 与 400 的两个通道都变成 255，看起来「已经平衡」）。
 *   200 留了 55 的余量给正常画面里的高光。
 * ③ 色偏上限：三个通道均值的 max/min 超过这个倍数就认为场景是单色的，不更新。
 *   200 = 2.00×。定这个数的依据：白平衡大体正确时，**普通混杂场景**（含人脸、
 *   木色家具、暖光）的通道均值比很少超过 1.7×，而单色场景轻易到 3× 以上 ——
 *   红墙 R200/G60/B55 ⇒ 3.6×，绿植 R55/G150/B50 ⇒ 3.0×，蓝天 R70/G110/B210
 *   ⇒ 3.0×，都被这条挡住。调小 = 更保守（更多正常场景也不更新），
 *   调大 = 开始被单色场景带偏。
 *   ⓘ 通道均值为 0 时按「无穷大色偏」处理（同时也顺手挡住了除零）。
 * ④ 增益合理范围：算出来的建议增益必须落在 [MIN, MAX] 之内，否则**这一拍
 *   整个不更新**（而不是钳到边界上采纳）—— 跑出这个范围本身就说明这份统计
 *   不可信，采纳一个钳过的值等于把错误的方向照走不误。
 *   下限 1.000 不是随便定的：Bayer 阵列 50% 是绿像素、绿滤光片透过率也最高，
 *   **绿通道恒为三者中最强**，所以 R/B 相对 G 的增益在物理上不可能小于 1。
 *   上限 3.000 覆盖到白炽灯（2700K，蓝通道很弱，B 增益约 2.5~3）；再往上
 *   就逼近硬件定点格式的 4.0 死线了，而且那种照明下噪声已经先崩。
 */
#define CAM_AWB_LUM_MIN        40
#define CAM_AWB_LUM_MAX        200
#define CAM_AWB_CAST_MAX_PCT   200
#define CAM_AWB_GAIN_MIN_MILLI 1000
#define CAM_AWB_GAIN_MAX_MILLI 3000

/* 连续这么多个更新周期落在死区内就报「收敛」。纯观测量，不参与控制。 */
#define CAM_AWB_CONVERGE_TICKS 3

/* ══════════════════════════════════════════════════════════════════════
 *  官方前馈画质级（开环查表，**不是闭环**）
 * ══════════════════════════════════════════════════════════════════════
 *
 * 官方 IPA 把 ISP 各画质级的参数按**当前工作点**查表下发，不带任何误差反馈
 * （adn / acc / aen 三个模块的表全部以 gain / color_temp / luma 为索引，没有误差
 *  项，见 docs/superpowers/research/2026-08-19-esp32p4-official-isp-pipeline.md §B.1）。
 * 我们照此办理：标定表在 cam_isp_cal.h（机械生成），查表逻辑在 cam_isp_map.c
 * （纯逻辑、宿主机可测），本文件只放开关与迟滞。
 *
 * ⚠️ **每一组前馈级各有一个编译开关，是为了能分别 bisect。** 现场若发现画面出
 *   问题，把其中一个改成 0 重编即可确定是哪一级 —— 关掉时该级**一行代码都不进
 *   镜像**（整段 #if 掉），硬件停在寄存器复位值，也就是本组前馈级上线之前那个
 *   已实机验证过的状态。**全部关掉的构建也必须能编过**，这条每次都验。
 */

/* T2：BF（Bayer 域降噪）+ Demosaic 梯度比，按传感器总增益分档。 */
#define CAM_ADN_ENABLE   1

/*
 * 前馈重配的迟滞：档位算出来变了，也要**连续**这么多拍都指向新档才真的下发。
 *
 * 为什么必须有：rev < 3.0 **没有影子寄存器**（isp_ll_shadow_update_* 在该分支里
 * 是恒真的空桩），参数写下去立刻生效、**没有帧边界原子性** —— 帧中途换 BF 模板
 * 会出现单帧的上下半张不同处理。AE 在档位断点上抖一下就重配一次的话，那种撕裂
 * 会以「偶发横向亮带」的形式出现，而且极难归因。
 * 3 拍 = 300 ms，与 AE 的更新周期（CAM_AE_INTERVAL_TICKS = 3）同量级，
 * 代价是换档慢 0.3 秒，肉眼不可见。自检行打「重配=」计数，它若随时间线性增长
 * 就说明迟滞没起作用（或者增益真的在持续变），先看这个数再去调它。
 */
#define CAM_FEEDFWD_HYST_TICKS  3

/* ══════════════════════════════════════════════════════════════════════
 *  自动曝光：数据结构与控制律
 * ══════════════════════════════════════════════════════════════════════ */

/*
 * 传感器给出的可调范围。全部**运行时向 esp_cam_sensor 查**（query_para_desc），
 * 不写死：曝光上限跟着 VTS 走，增益表长度跟着 menuconfig 的
 * CONFIG_CAMERA_SC202CS_ABSOLUTE_GAIN_LIMIT 与增益优先策略走，抄成常量必然过期。
 */
typedef struct {
    uint32_t exp_min;          /* 曝光寄存器值下限 */
    uint32_t exp_max;          /* 上限 */
    const uint32_t *gain_map;  /* 绝对增益表（单调升，单位 1/1000），传感器组件持有 */
    uint32_t gain_count;       /* 表长；**合法下标只到 gain_count − 1**，见下面 ⚠️ */
} cam_ae_limits_t;

/*
 * AE 状态机。曝光与增益两个旋钮被合成一个标量 **ev（曝光量）**：
 *     ev = 曝光寄存器值 × 绝对增益 ÷ 1000
 * 亮度与 ev 成正比（在不削顶的范围内），所以控制律只需要对这一个数做比例控制，
 * 「先用曝光时间、不够再加增益」的分配策略被隔离在 cam_ae_split() 里 ——
 * 控制与分配分开，两件事各自可测。
 */
typedef struct {
    uint32_t ev;          /* 当前曝光量（**量化后的实际值**，不是请求值，见 cam_ae_step） */
    uint32_t exposure;    /* 已下发的曝光寄存器值 */
    uint32_t gain_index;  /* 已下发的增益档位下标 */
    uint32_t settle;      /* 还要跳过几拍才允许再动（更新频率限制） */
    uint32_t in_band;     /* 连续落在死区内的次数，到 CAM_AE_CONVERGE_TICKS 封顶 */
    uint32_t updates;     /* 累计真正下发过多少次，自检行用 */
    uint8_t  last_mean;   /* 最近一次看到的亮度均值，自检行用 */
} cam_ae_state_t;

/* 曝光量 = 曝光寄存器值 × 绝对增益(1/1000)。溢出安全：1244 × 63008 仍在 uint32 内。 */
uint32_t cam_ae_ev(uint32_t exposure, uint32_t gain_milli);

/*
 * 把一个曝光量拆成 (曝光寄存器值, 增益档位)。
 *
 * 策略：**曝光时间优先，增益垫底** —— 曝光时间不增加噪声，模拟/数字增益都增加。
 * 只有当曝光顶到 exp_max 还不够亮时才开始往上翻增益档。
 * 增益档取「不超过所需值的最大一档」（表单调升），并同时受 CAM_AE_GAIN_MAX_MILLI 约束。
 *
 * ⚠️ 下标严格落在 [0, gain_count − 1]。**不能指望传感器驱动兜底**：
 *    sc202cs.c:1167 的 `MIN(u32_val, s_limited_abs_gain_index)` 是个 off-by-one ——
 *    当增益表里没有任何一项超过 CONFIG_CAMERA_SC202CS_ABSOLUTE_GAIN_LIMIT 时
 *    （默认恰好如此：表的最大值 63008 == 上限 63008，:1526-1532 那个循环从不 break），
 *    s_limited_abs_gain_index 停在 ARRAY_SIZE 上，于是下标 == 表长也被放行，
 *    sc202cs_gain_map[表长] 是一次**越界读**。传进去的数必须自己保证合法。
 *
 * ev 为 0 或 limits 非法时输出下限档，不会除零。
 */
void cam_ae_split(uint32_t ev, const cam_ae_limits_t *lim,
                  uint32_t *exposure, uint32_t *gain_index);

/* 用传感器的默认曝光/增益初始化状态机（它们此刻就是芯片里的实际值）。 */
void cam_ae_init(cam_ae_state_t *st, const cam_ae_limits_t *lim,
                 uint32_t exposure, uint32_t gain_index);

/*
 * 走一拍。**每帧都要调**（频率限制在函数内部做，不由调用方判断）。
 *
 * 返回 true 表示 st->exposure / st->gain_index 变了、需要下发给传感器；
 * 返回 false 表示这一拍不动（没到更新周期 / 落在死区 / 已经顶到上下限 /
 * 量化后落回同一档）—— 调用方**不要**在 false 时下发，那等于把 I2C 事务
 * 白白撒在总线上（这条总线还挂着 20 ms 轮询的触摸）。
 *
 * 四道防振荡闸的位置见上面各常量的注释。除此之外还有一条：state 里存的 ev 是
 * **量化后的实际曝光量**而不是请求值，否则每次请求与实际的那点差额会在下一拍
 * 被当成新的误差再放大一次，形成慢速极限环。
 */
bool cam_ae_step(cam_ae_state_t *st, uint8_t lum_mean, const cam_ae_limits_t *lim);

/* 是否已收敛（连续 CAM_AE_CONVERGE_TICKS 次落在死区内）。 */
bool cam_ae_converged(const cam_ae_state_t *st);

/* ══════════════════════════════════════════════════════════════════════
 *  白平衡：从实测通道均值反推 CCM 系数
 * ══════════════════════════════════════════════════════════════════════ */

/*
 * 由「当前生效的 CCM 增益」+「当前画面的分通道均值」算出**绝对**的建议增益。
 *
 *     建议 = 当前 × g_mean / 该通道均值
 *
 * 之所以要乘上当前值：均值是**施加 CCM 之后**测到的，直接拿 g/r 当增益就把
 * 已经生效的那一份又算了一遍，越调越偏。乘进去之后这个式子是**幂等**的 ——
 * 系数正确时三个均值相等，建议值恰好等于当前值，不会来回摆。
 *
 * 只在镜头对着白/灰面时有意义（灰世界假设）。红通道均值为 0（全黑/纯蓝画面）时
 * 该通道保持当前值不变，不会除零、也不会给出一个荒唐的建议。
 * 输出限幅到 [250, 4000]：上限是硬件定点格式的 4.0，下限防止一次误测把系数打到 0。
 */
void cam_awb_suggest(uint8_t r_mean, uint8_t g_mean, uint8_t b_mean,
                     uint32_t cur_r_milli, uint32_t cur_b_milli,
                     uint32_t *sug_r_milli, uint32_t *sug_b_milli);

/* ══════════════════════════════════════════════════════════════════════
 *  白平衡：闭环 AWB 的状态机与控制律
 * ══════════════════════════════════════════════════════════════════════ */

/*
 * 一拍的结论。**「没更新」必须能分出是被哪一条挡的** —— 否则现场只能看到
 * 「颜色不动」，说不清是场景被判成单色、还是太暗、还是已经收敛了。
 * 顺序 = 判据在 cam_awb_step() 里的先后，自检行按这个顺序打计数。
 */
typedef enum {
    CAM_AWB_APPLIED = 0,   /* 增益变了，调用方必须把新的 CCM 写进 ISP */
    CAM_AWB_SKIP_AE,       /* AE 还没收敛：亮度在变，颜色统计不作数 */
    CAM_AWB_SKIP_DARK,     /* 防护①：画面太暗，噪声主导 */
    CAM_AWB_SKIP_BRIGHT,   /* 防护②：画面太亮，通道被削顶截断 */
    CAM_AWB_SKIP_CAST,     /* 防护③：色偏过大，八成是单色场景 */
    CAM_AWB_SKIP_PERIOD,   /* 场景可信，但还没到更新周期 */
    CAM_AWB_SKIP_BAND,     /* 落在死区内：已经平衡，不用动 */
    CAM_AWB_SKIP_RANGE,    /* 防护④：建议增益跑出合理范围，统计不可信 */
    CAM_AWB_SKIP_QUANT,    /* 阻尼/限幅后整数运算落回原值，没有实际变化 */
    CAM_AWB_REASON_COUNT,
} cam_awb_reason_t;

/*
 * AWB 状态机。两个旋钮就是 CCM 对角线上的 R 与 B（G 恒为 1.000 作基准）。
 * reasons[] 是纯观测量：每一拍的结论各计一次，自检行直接打出来 ——
 * 「AWB 没在动」有八种原因，靠这个直方图一眼分清。
 */
typedef struct {
    uint32_t gain_r_milli;                  /* 当前 R 增益（= 已写进 CCM 的值） */
    uint32_t gain_b_milli;                  /* 当前 B 增益 */
    uint32_t settle;                        /* 还要跳过几拍才允许再动 */
    uint32_t in_band;                       /* 连续落在死区内的周期数，到上限封顶 */
    uint32_t updates;                       /* 累计真正改过多少次增益 */
    uint32_t reasons[CAM_AWB_REASON_COUNT]; /* 每种结论各出现过多少次 */
    cam_awb_reason_t last;                  /* 最近一拍的结论 */
    uint8_t  last_r, last_g, last_b;        /* 最近一拍看到的通道均值 */
} cam_awb_state_t;

/* 初始化到静态标定值（CAM_CCM_GAIN_R/B_MILLI）—— 开机头几拍的颜色由它决定。 */
void cam_awb_init(cam_awb_state_t *st);

/*
 * 走一拍。**每帧都要调**（频率限制在函数内部做，不由调用方判断）。
 * 返回 CAM_AWB_APPLIED 表示 st->gain_r/b_milli 变了、必须重配 CCM；
 * 其余返回值都表示这一拍不动，值本身说明为什么。
 *
 * ══ 为什么反馈量是**归一化**的通道比值 ══════════════════════════════
 *
 * 控制律的核心是 cam_awb_suggest()：建议增益 = 当前增益 × g_mean / 该通道均值。
 * 这个式子里只有**比值**，没有绝对亮度 —— AE 把曝光量翻一倍，三个通道均值
 * 一起翻倍，比值不变，建议值也不变。
 * ⇒ **AWB 对 AE 的动作天然免疫**，这是两个环解耦的第一条措施（另外两条是
 *   周期分离与下面的 ae_converged 闸）。反过来「AWB 改 CCM 会让画面变亮、
 *   扰动 AE」这个方向没法靠数学消掉，只能靠时间尺度分离 —— 好在这个方向是
 *   良性的：AE 会把多出来的亮度调回去，而调回去又不影响 AWB 的比值。
 *
 * ae_converged：AE 是否已收敛。传 false 时这一拍直接跳过（CAM_AWB_SKIP_AE）。
 *   ⚠️ 这不是「AWB 依赖 AE」，而是**只在亮度稳定的窗口里采信颜色统计**：
 *      曝光正在大幅调整时画面要么欠曝（噪声大）要么过曝（削顶），两种都会把
 *      通道比值带偏。AE 关着（查不到可调范围）时曝光是恒定的，调用方应当
 *      直接传 true —— 恒定曝光本身就是「亮度稳定」。
 */
cam_awb_reason_t cam_awb_step(cam_awb_state_t *st, uint8_t lum_mean,
                              uint8_t r_mean, uint8_t g_mean, uint8_t b_mean,
                              bool ae_converged);

/* 是否已收敛（连续 CAM_AWB_CONVERGE_TICKS 个周期落在死区内）。 */
bool cam_awb_converged(const cam_awb_state_t *st);

/* 结论的中文说法，给自检行用。任何输入都返回非空字符串。 */
const char *cam_awb_reason_str(cam_awb_reason_t r);
