/*
 * ── 白平衡：CCM 对角线增益的**开机初值**，单位 1/1000 ────────────────
 *
 * 施加到 ISP 的矩阵是 diag(R, G, B)/1000，绿固定 1.000 作基准，红蓝往上抬
 * （而不是把绿压下去）：抬红蓝时绿通道保持满量程，压绿则要靠 AE 多加一档增益
 * 才能补回亮度，白白多一份噪声。上限 4.0 是硬件定点格式给的，见文件头。
 *
 * ⓘ **这三个数现在只是初值。** 闭环 AWB（下一节）开机后会从这里出发、
 *   按画面实测的通道均值把 R/B 调到位。它们仍然重要：
 *     · 开机最初一两秒 AWB 还没收敛，画面颜色由它们决定 —— 从一个大体对的
 *       地方出发，比从 1.000 出发少几拍、也不会让用户看到一段乱跳的颜色；
 *     · CAM_AWB_ENABLE = 0（钉回纯静态）时它们就是最终值；
 *     · 场景一直不可信（单色/太暗）时 AWB 一步都不走，画面停在它们身上。
 *
 * ⚠️ 默认值是估计值，不是实测值。想把它们量准（或者要退回纯静态档）时：
 *
 *      1. 烧板，让摄像头对着一张**白纸**（或灰卡），照明用日常那盏灯，充满画面；
 *      2. 等 AE 收敛（自检行「AE ... 收敛」且亮度均值落在目标附近 —— 曝光没稳时
 *         通道均值也没意义）；
 *      3. 读 camera 的自检行：
 *            [自检] 画质 CCM=... 当前 R×1.700 G×1.000 B×1.550
 *                   | 通道均值 R98 G121 B105 → 建议 CCM R×2.099 B×1.786
 *         最后那两个数已经把「当前生效的 CCM」算进去了（是**绝对**建议值，
 *         不是增量），直接抄进下面两行重新编译即可；
 *      4. 再跑一次，通道均值应当三个数相近（差 <5%），建议值应当≈当前值。
 *
 *    ⓘ AWB 开着的时候这一步会**自动**发生：自检行里的「当前」就是 AWB 调出来的
 *      值，抄它就等于把闭环的结论固化成静态标定。
 *
 * ⓘ 只做对角线、不做非对角项：非对角项管的是色彩还原准确度（把传感器的光谱响应
 *   映射到 sRGB），需要色卡与拟合，与「发绿」这个问题无关，刻意不做。
 */
#define CAM_CCM_GAIN_R_MILLI   1700
#define CAM_CCM_GAIN_G_MILLI   1000
#define CAM_CCM_GAIN_B_MILLI   1550

/*
 * ══════════════════════════════════════════════════════════════════════
 *  T10：CCM 的形态 —— 对角阵 → 官方 19 档色温标定矩阵
 * ══════════════════════════════════════════════════════════════════════
 *
 * 0 = 对角阵 diag(kr, 1, kb)。**只做白平衡、不做色彩还原**，即 T9 之前那条
 *     已实机验证过的路径。
 * 1 = 官方 19 档色温标定矩阵按 CCT 逐元素线性插值，再把白平衡增益**右乘**折进去。
 *
 * ══ 为什么右乘折叠是对的（不是将就）══════════════════════════════════
 *
 * 官方标定矩阵每一行的系数之和都是 1.000（cam_isp_cal.h 里由提取脚本逐档断言），
 * 其前提是白平衡已经由 WBG 在 RAW 域做掉。本板 rev v1.0 没有 WBG，于是走官方
 * rev<3.0 的同一条降级路：
 *
 *     P = M · diag(kr, 1, kb)
 *
 * WBG 与 demosaic 都是**逐通道的线性算子、可交换**，所以这个右乘与「先 WBG
 * 再 CCM」数学等价。而且对中性面 w = (1/kr, 1, 1/kb) 有
 *
 *     P · w = M · (1,1,1)ᵀ = (行和, 行和, 行和)ᵀ = (1,1,1)ᵀ
 *
 * ⇒ **「行和为 1」这个标定前提被右乘完整保持**：中性面进去仍然中性面出来，
 *   整体增益仍然精确为 1，白纸还是白纸。（本次实施独立验算过 19 档 × 3 组增益。）
 *
 * 真正被右乘破坏的只有**定点范围**：rev v1.0 的 CCM 是 S2.10（2 整数位 + 10 小数位
 * + 符号），系数上限 4.0，而官方 2292 K 那一档本身就含 4.5445 —— 折进 kb = 3.44
 * 之后最大系数会到 15.6。解法是下面的强度参数，**不是**把矩阵整体缩小。
 *
 * ══ 回退 ════════════════════════════════════════════════════════════
 * 改成 0 立刻回到对角阵，即 T9 之前已实机验证的色彩表现；自检行仍然照打
 * （模式那一格会说「对角阵」），CCT 估计也仍然在，现场能继续对照着看。
 */
#define CAM_CCM_MODE  0

/*
 * ── 色彩还原强度的上限（0..256，256 = 官方矩阵全量）─────────────────
 *
 * 实际强度 t 由 cam_ccm_fold_wb() 二分求出：取满足 9 个系数全部 |v| <= 3.990
 * 的**最大** t，其中 M(t) = (1−t)·I + t·M。本宏是这个 t 的**总闸**（取两者较小者）。
 *
 * 为什么是「朝单位阵混合」而不是「整体乘一个 α 缩小」：
 *   · M(t) 的行和恒为 1 ⇒ 白还是白、整体增益精确为 1，**一点亮度都不损失**；
 *     整体缩放则要 AE 补 1/α 的曝光（2292 K 档 α = 0.256 ⇒ 多 2 EV 噪声，
 *     而低色温场景本来就暗，正是最不该加噪声的地方）。
 *   · t = 0 时 P 退化成 diag(kr, 1, kb) —— **正是本改动之前已实机验证过的那条
 *     路径**。钳到底的「最坏情况」就是「回到已知可用状态」，不引入新的失败模式。
 *
 * 实测参考（用官方白点轨迹反推的自洽增益，计划 §D.4）：4193~5770 K 原样装得下
 * （t* = 256）；6000/6554 K 需 t* ≈ 241/225；3800 K 212；3473 K 166；3055 K 107；
 * 2517 K 26；2292 K 10。
 *
 * ══⛔ 默认值 192 是**降级档**，等 T7 的黑电平实测数据回来才能定 ⛔══════
 *
 * T10 的判定点是 T7 的黑位实测（cam_tune.h 的 CAM_SENSOR_BLC_ENABLE 那一节），
 * 而**那个数还没有** —— 量具已经交付（自检行「黑位」那一行），但要用户盖住镜头、
 * 等 AE 顶格之后读一次。在拿到它之前，这里按最保守的那一档取值。
 *
 * | 盖镜头 + AE 顶格后「线性最暗 r/g/b」 | CAM_CCM_STRENGTH_MAX | CAM_STAT_BLC_PEDESTAL |
 * |---|---|---|
 * | 都 <= 3（基座 ≈ 0）                  | **256**（放行，官方矩阵全量） | 0（保持） |
 * | 写 0xc0 无效 / 仍 ≈ 16               | **192**（本默认值）           | **16**（打开统计侧减法） |
 * | > 30 且查不出原因                    | 走 `CAM_CCM_MODE 0`，T10 整个不做 | 0 |
 *
 * 为什么黑位大就得压强度：一个**等值**基座 p 会被 W = diag(kr,1,kb) 变成**不等值**
 * 的 (kr·p, p, kb·p)，再被官方 CCM 的大负非对角项放大 —— 5040 K + kr1.8/kb1.85 +
 * p = 16 时约 (+23, −8, +21)，也就是**可见的品红色黑位**。压 t 直接按比例压掉这一份
 * 放大（t = 0 时非对角项全为 0 ⇒ 基座只被 W 缩放，不再串色）。
 *
 * ⚠️ **注意 CAM_STAT_BLC_PEDESTAL 我没有跟着改成 16**，尽管上表把它和 192 列在
 *   同一行。理由：压强度在任何基座下都只会更安全（t 越小越接近已验证的对角阵），
 *   而**减去一个没量过的基座会主动把 rg/bg 推偏**（那一节的 ⚠️ 已经写明「填 16
 *   之前必须先量出基座确实 ≈16」）—— 它不是保守，是一次押注。所以两个参数的
 *   默认取向不同：强度取降级档，减法保持 0（= T9 已验证的行为）。
 *   拿到 T7 数据后按上表把两个数一起改成对应那一行。
 */
#define CAM_CCM_STRENGTH_MAX  192

/*
 * ── 没有可信 CCT 估计时用的色温，单位 K ────────────────────────────
 *
 * 硬件白点统计还没给出过一次可用采样时（开机头一秒、CAM_AWB_STAT_ENABLE = 0、
 * 或白点一直不够）CCM/LSC/饱和度都拿这个数去查表。
 *
 * 取 5210 而不是别的：它同时是 **LSC 三档的中间档**（cam_cal_lsc_cct[1]）与
 * **CCM 19 档里最接近日光的那一档**（cam_cal_ccm_cct[11] = 5210）——
 * 三个前馈级用同一个默认值，「没有 CCT 时的行为」就只有一种，不必分别推理。
 * 数值本身来自官方标定表，不是我们挑的。
 */
#define CAM_CCT_DEFAULT_K     5210

/*
 * ── AE 的反馈量来源（T6）──────────────────────────────────────────
 *
 * 0 = 软件全帧 1/64 抽样的**线性**亮度均值（cam_frame_stats 的 lin_lum_mean，
 *     采在 ISP **输出**：CCM/Color 下游，gamma 由逆表还原）
 * 1 = ISP 硬件 5×5 分块统计的**官方加权均值**（采在 **demosaic 之后**，
 *     官方 esp_video 硬编码的采样点；权重表与两个 quorum 都是官方原值）
 *
 * ══ 为什么换 ══
 *
 * ① **官方那套数只有在这个采样点上才成立。** target 62、死区 56/64、
 *    low_threshold 14 / low_regions 5、high_threshold 239 / high_regions 3、
 *    25 个权重 —— 全部是在 AFTER_DEMOSAIC 上标的（cam_isp_cal.h）。
 *    换句话说：**不换源，那些数就只是一串抄来的数字。**
 * ② **两个环真正解耦。** 硬件采样点在 CCM **上游** ⇒ AWB 改 CCM 对角线、
 *    gamma 换档，都扰不到 AE 的输入（今天软件口径要靠逆 gamma 表才做到一半）。
 * ③ **空间信息。** 过暗/过亮块的 quorum 剔除要有分块才谈得上，全帧均值没有。
 *
 * ══ ⚠️ 换源之后画面会变亮约 1/ρ ≈ 1.27×，这**不是回归**══
 *
 * 本板 rev v1.0 没有 WBG，白平衡是拿 CCM 对角线 diag(1.7, 1.0, 1.55) 做的
 * ——「WB 在 demosaic 之后」正是官方 rev<3.0 降级路径的做法
 * （esp_video_isp_device.c 的 isp_init_ccm_param()，把 R/B 增益乘进 CCM 的第 0/2 列）。
 * 于是 **AE 的硬件采样点在白平衡的上游**，而我们原来的软件统计采在它下游：
 *     软件线性均值 ≈ 硬件加权 × (0.30·kr + 0.586·kg + 0.113·kb)
 *                  = 硬件加权 × (0.30×1.7 + 0.586 + 0.113×1.55) = 硬件加权 × 1.271
 * ⇒ 预测 ρ = 硬件/软件 ≈ 0.79（再乘上中心加权带来的那点场景相关偏差）。
 * 也就是说：**旧口径下写 62，实际是把 WB 放大过的亮度顶到 62，等价于把真实
 * （WB 前）亮度压到 49 —— 一直在系统性欠曝 27%。** 换源之后同一个 62 落到
 * 正确的域上，画面会亮回来：线性 62 → 79，经 γ=0.5 编码后主机看到的是 126 → 142
 * （+13%，看得出来但很温和）。
 *
 * ⚠️ **这一条与原计划 T6 Step 2 相反，必须记下来。** 计划写的是「换源必须按 ρ
 *   缩放目标以保持观感不变」（旧目标 120 × 0.79 = 95），那套算术的前提是
 *   「旧目标是我们自己拍脑袋定的、没有权威含义」。751b24bb 把目标改成官方的 62
 *   之后前提就没了：62 本来就是新口径下的权威值，**再乘一次 ρ 等于把它搬回
 *   错误的域**。所以这里不缩放。
 *   若实机觉得偏亮：先确认自检行的 ρ 稳定在 0.79 附近（这验证了上面的推导），
 *   再决定是接受官方值，还是把 CAM_AE_TARGET 改成 round(62·ρ) ≈ 49 回到 T5 的观感
 *   —— 但那就不是「对齐官方」了，改的时候把理由写进这里。
 *
 * 回退：设 0 立刻回到 T5 已实机验证的软件均值路径（统计块仍然建、仍然打日志），
 * 目标与死区也一并退回对称形式，无需改别的地方。
 * ⚠️ 依赖 CAM_AE_STAT_ENABLE = 1；不相容的组合由 camera_csi.c 的 #error 拦下。
 */
#define CAM_AE_SOURCE          1

/*
 * ── 自动曝光 ────────────────────────────────────────────────────────
 *
 * 目标亮度：**线性域** BT.601 亮度均值的期望值。62 = 官方 SC202CS 标定的
 * agc.luma_adjust.target（cam_isp_cal.h 的 CAM_CAL_AE_TARGET，死区 56~64）。
 *
 * ══ 为什么从 120 改成 62 ══
 *
 * 120 是我们自己拍脑袋定的「8 位量程中位偏上」，而实测这颗传感器在室内**只到
 * 45** ⇒ AE 永远够不着目标 ⇒ 曝光顶格、增益一路推到 CAM_AE_GAIN_MAX_MILLI，
 * 换回来的仍然是一张暗图，只是**噪声按满增益的量级**。用户实拍看到的「噪声重」
 * 正是这个：目标定得够不着，代价全部由增益承担。
 * 改成 62 之后，中等光照下 AE 能真正落在死区里停下来，增益不必顶满。
 *
 * ⓘ **T6 已经把测光换成官方口径，这个 62 从「过渡值」变成了「官方原值」。**
 *   它现在与 cam_cal_ae_target（cam_isp_cal.h）**同源同域**：都指
 *   ISP_AE_SAMPLE_POINT_AFTER_DEMOSAIC 上的 5×5 中心加权亮度。
 *   camera_csi.c 里有一条 _Static_assert 把这两个数钉在一起，改一个不改另一个
 *   会在编译期被拦下。CAM_AE_SOURCE = 0 时它退回「软件全帧线性均值的目标」，
 *   两种口径共用同一个数字只是巧合，量纲说明见 CAM_AE_SOURCE 那段。
 *
 * ⓘ 量纲是**线性域**：ISP 的 gamma 开着时画面本身是 gamma 编码的，但送进控制律
 *   的是 cam_frame_stats 的 lin_lum_mean（逆表还原过），所以这个数的含义与
 *   gamma 开关无关 —— 这正是「统计侧逆 gamma」要保住的东西。
 *   线性 62 经 γ=0.5 那档曲线编码后主机看到的是 126，正是一张曝光正常的图。
 */
#define CAM_AE_TARGET          62

/*
 * ── 高光/暗部优先：对目标亮度的偏移（T12）──────────────────────────
 *
 * 官方 agc.{high,low}_light_priority.luma_offset：
 *   高光优先 −3 ⇒ 目标 59（保高光不过曝，官方 agc.mode 对这颗传感器就是它）
 *   暗部优先 +1 ⇒ 目标 63（保暗部细节）
 * 与官方那个非对称死区（−6/+2）取向一致：过曝会削顶，削顶丢掉的信息任何后级
 * 都补不回来；偏暗只是噪声大一点，还能靠 gamma 提回来。
 *
 * ⓘ 官方那两块里还各有一个 weight_offset（对落在某亮度区间的块加权 +5），
 *   以及 light_threshold_priority[5] 的阶梯表 —— **触发条件与叠加方式是 [缺口]**，
 *   猜错的加权比不加权更坏，所以本工程**只取 luma_offset**。
 *
 * ⚠️ 这两个数是**偏移**不是目标：死区跟着目标平移（低边 −6、高边 +2），
 *   由 cam_ae_target() 与 cam_ae_step() 一起保证，不在调用处各算一遍。
 */
#define CAM_AE_HL_OFFSET       (-3)
#define CAM_AE_LL_OFFSET       (1)

/*
 * ── 背光（逆光）判据 ────────────────────────────────────────────────
 *
 * 官方的模式选择器（agc.mode 那一串字符串背后的逻辑）是**闭源缺口**，这是我们
 * 给出的可解释版本：**「画面里有一大片很亮的东西，而整体却偏暗」**——
 * 这正是逆光的定义（人站在窗前）。两个量都来自同一次直方图采样：
 *   亮块占比 = 最高那个 bin（>=240）的占比（cam_hist_stats 的 bright_pct）
 *   场景均值 = 直方图的近似均匀加权均值（= 官方 ian.luma.env 的口径）
 * 判据：亮块 >= 25% **且** 场景均值 < CAM_AE_TARGET_LOW(56) ⇒ 切暗部优先。
 *
 * ⚠️ 25% 与 target_low 这两个门限是**我们定的，不是官方的** —— 所以放在这里
 *   而不是 cam_isp_cal.h（那个文件只装机械提取的官方数据）。
 *   现场若发现从不触发，先看自检行里的「亮块=」实测值再按实测调，
 *   **并把「这个数是实测调的」写进本注释**。
 *
 * ⓘ 只有一个门限（不带迟滞）：两个目标只差 4 级（59 ↔ 63），而 AE 死区宽 8 级
 *   ⇒ 判定翻转最多让 AE 多走一步就重新落进死区，不会形成振荡。
 *   真在边界上抖的话自检行的「背光=」会来回变，那时再加迟滞。
 * ⚠️ 关掉（= 0）时恒取高光优先（目标 59），即官方对这颗传感器的默认模式。
 */
#define CAM_BACKLIGHT_ENABLE      1
#define CAM_BACKLIGHT_BRIGHT_PCT  25

/*
 * 死区：|均值 − 目标| ≤ 这个数就完全不动。**防振荡的第一道闸**。
 *
 * 6 = 目标的 10%，与目标从 120 改到 62 之前那个 12 保持**同一个比例** ——
 * 死区的作用是「小于这个差别肉眼看不出」，它是相对量，跟着目标缩放才守恒；
 * 留在 12 上的话相对死区会从 10% 变成 19%，AE 会在 50~74 之间的任何一处停下，
 * 那是一次没人要求过的行为改变。
 *
 * ⓘ 本常量只在 `CAM_AE_SOURCE = 0`（软件口径）下使用。硬件口径下死区直接取官方的
 *   **非对称**区间 [56, 64]，见下面 CAM_AE_TARGET_LOW/HIGH。
 */
#define CAM_AE_DEADBAND        6

/*
 * ── 死区的实际边界（控制律只认这两个数）───────────────────────────
 *
 * 拆出 LOW/HIGH 而不是继续用「目标 ± 死区」，是因为**官方的死区是非对称的**：
 * agc.luma_adjust 给的是 target 62 / low 56 / high 64，即 −6/+2。
 * 官方为什么偏紧上侧：过曝会削顶，削顶丢掉的信息任何后级都补不回来，
 * 而偏暗只是噪声大一点、还能靠 gamma 提回来 —— 这个不对称是有物理含义的，
 * 不是标定噪声，所以对齐时必须连不对称一起对齐。
 *
 * ⚠️ 这两个数与 CAM_AE_SOURCE **绑定**：换源必须换数（它们是同一个采样点上的量）。
 *   CAM_AE_SOURCE = 0 时退回原来的对称死区，行为与 T6 之前逐位一致。
 * ⚠️ 恒有 LOW <= TARGET <= HIGH，由 test_cam_tune.c 的可调参数自检守着。
 */
#if CAM_AE_SOURCE
#define CAM_AE_TARGET_LOW      56
#define CAM_AE_TARGET_HIGH     64
#else
#define CAM_AE_TARGET_LOW      (CAM_AE_TARGET - CAM_AE_DEADBAND)
#define CAM_AE_TARGET_HIGH     (CAM_AE_TARGET + CAM_AE_DEADBAND)
#endif

/*
 * 阻尼：每次只走到「理论正确值」的 NUM/DEN。**防振荡的第二道闸**。
 * 取 1/2 的理由：测量到执行之间有约 170 ms 的滞后（推导见 CAM_AE_INTERVAL_TICKS），
 * 一个带滞后的比例环节，增益 1.0 就在振荡边缘，0.5 留一倍余量，代价只是多花
 * 一两拍收敛。**不要**改成 1/1「让它快点」。
 */
#define CAM_AE_DAMP_NUM        1
#define CAM_AE_DAMP_DEN        2

/*
 * 单步限幅：一次最多把曝光量放大/缩小这个倍数。**防振荡的第三道闸**。
 * 场景骤变（盖住镜头 ⇒ 均值 2）时理论倍数会到 60×，一步跳过去必然大幅过冲、
 * 然后反向再来一次，正是最难看的那种喘。限成 2× 后最坏情况约 6 步（≈2 秒）
 * 走完 60×，全程单调、不过冲。
 */
#define CAM_AE_STEP_MAX        2

/*
 * 增益上限，单位 1/1000。传感器自己的表能到 63×（噪声已经盖过画面），
 * 这里按「还看得出是画面」压到 16×。**欠曝时先加曝光时间再加增益**，
 * 所以这个上限只在很暗的场景才起作用。
 * 下限恒为增益表第 0 档（1.000×），不单设常量：低于 1× 传感器表里就没有。
 */
#define CAM_AE_GAIN_MAX_MILLI  16000

/*
 * 更新频率限制：每这么多拍才允许动一次曝光。**防振荡的第四道闸**。
 * 一拍 = UVC 帧泵的一帧 = 100 ms（10 fps），所以 3 拍 = 300 ms。
 *
 * 这个数由**测量滞后**定，不能凭感觉调小：
 *   传感器把新曝光值应用到下一帧          ≈ 1~2 帧 @30fps =  33~66 ms
 *   CSI 侧最多积压 2 帧才轮到我们取走      ≈           至多  66 ms
 *   帧泵自己 100 ms 一拍                    ≈           至多 100 ms
 *   合计最坏 ≈ 230 ms ⇒ 取 300 ms，保证**每次测量都反映的是上一次下发的结果**。
 * 调小到 1 拍的话，前两次测量还是旧曝光下的画面，控制器会以为「没效果」而继续
 * 加码 —— 这是曝光振荡最经典的成因，比例增益再小也救不回来。
 */
#define CAM_AE_INTERVAL_TICKS  3

/* 连续这么多次落在死区内就报「收敛」。纯观测量，不参与控制。 */
#define CAM_AE_CONVERGE_TICKS  3

/*
 * ── AE 的硬件 5×5 分块统计（ISP AE 统计块）─────────────────────────
 *
 * T5：**上线但不接管** —— 统计块建起来、每帧把 25 块亮度搬进内存、自检行打出来，
 * 控制律仍吃软件全帧均值。T6 才把 `CAM_AE_SOURCE` 翻成 1 让它接管。
 * 本开关与 CAM_AE_SOURCE 是**两件事**：这个管「统计跑不跑」，那个管「谁在用」。
 * 保持这个分离，是为了 CAM_AE_SOURCE = 0 回退之后**自检行里的 ρ 还在**，
 * 现场能继续拿两个口径对比着看，而不是一退就瞎。
 *
 * 存在的理由只有一个：**换测量口径会改变 AE 的工作点**，而这三样东西一起变 ——
 *   采样点   软件统计采在 ISP **输出**（CCM/gamma/Color 全部下游，再由逆 gamma
 *            还原回线性）；硬件统计采在 **demosaic 之后**（CCM 上游，官方
 *            esp_video 硬编码的位置，esp_video_isp_device.c:879）。
 *   空间权重 软件是全画面均匀 1/64 抽样；硬件是官方 5×5 中心加权金字塔。
 *   剔除规则 软件没有；硬件带过暗/过亮块的 quorum 剔除。
 * 三者叠起来，同一个场景两种口径给出的数**必然不同**。差多少不能靠推理，
 * 只能实测 —— 这就是自检行里那个 **ρ = 硬件加权 / 软件线性均值**。
 * 先量一版、再据此切换，是本工程反复验证有效的纪律（T2~T4、gamma 都是这么做的）。
 *
 * ⚠️ ρ 的分母必须是 **lin_lum_mean**（逆 gamma 还原过的线性亮度），不是 lum_mean。
 *   硬件采样点在 gamma **上游**，本来就是线性量；拿 gamma 域的均值去比会把
 *   γ=0.5 那条曲线的整体抬升（62 → 126，约 2×）算进 ρ 里，得到一个纯属虚构的
 *   0.4 左右的比值。（gamma 是在本计划里**提前**做掉的，原计划 T5 那条
 *   「ρ = 硬件/软件全帧」写在 gamma 之前，直接照抄会错一倍。）
 *
 * 关掉（= 0）时整个统计块一行代码都不进镜像，硬件不建 AE 控制器、不申请 ISP
 * 中断，行为与 T5 之前逐位一致 —— 这是现场 bisect 的退路。
 * ⚠️ `CAM_AE_SOURCE = 1` 依赖本开关；两者不相容时由 camera_csi.c 的
 *   `#error` 在编译期拦下，别让它在运行期表现成「AE 永远拿全 0 去调曝光」。
 */
#define CAM_AE_STAT_ENABLE     1

/*
 * ── 自动白平衡（闭环，灰世界假设）──────────────────────────────────
 *
 * 总开关。**默认开**。设成 0 就钉回纯静态标定（CCM 开机配一次、之后一动不动，
 * 也就是这一改动之前那个已经实机验证过的状态）—— AWB 出任何问题时的退路，
 * 一行改动、不必回滚代码。设成 0 时 cam_awb_step() 相关的代码在 camera_csi.c
 * 里整段不编译，运行期开销为零。
 */
#define CAM_AWB_ENABLE         1

/*
 * ── AWB 的硬件白点统计（ISP AWB 统计块）───────────────────────────
 *
 * T8：**上线但不接管** —— 统计块建起来、每秒 oneshot 触发一次、把
 * counted/Σr/Σg/Σb 与推出的 rg/bg/CCT 打进自检行，**控制律一行不改**，
 * 仍然吃软件灰世界。T9 才把 CAM_AWB_SOURCE 翻成 1 让它接管。
 * 本开关与 CAM_AWB_SOURCE 是**两件事**：这个管「统计跑不跑」，那个管「谁在用」。
 * 保持这个分离，是为了 CAM_AWB_SOURCE = 0 回退之后自检行里那组**并排对照**
 * （硬件绝对增益 vs 软件灰世界绝对建议）还在，现场能继续两个口径对着看。
 *
 * 存在的理由与 CAM_AE_STAT_ENABLE 那一步完全同构：换估计器会同时改变三样东西 ——
 *   采样点   软件采在 ISP **输出**（CCM 下游，再逆 gamma 回线性）；
 *            硬件采在 **CCM 之前**（官方 esp_video 硬编码的采样点）。
 *   筛选     软件是整幅均值（灰世界）；硬件按官方白点框逐**像素**筛。
 *   公式     软件是闭环增量（× cur），硬件是开环绝对（不许 × cur）。
 * 三者叠起来结果**必然不同**，差多少不能靠推理 —— 所以先量一版再切。
 *
 * 关掉（= 0）时整个统计块一行不进镜像：不建 AWB 控制器、不申请 ISP 中断、
 * 帧泵里不做那次阻塞式 oneshot，行为与 T8 之前逐位一致。
 * ⚠️ `CAM_AWB_SOURCE = 1` 依赖本开关，不相容的组合由 camera_csi.c 的 `#error`
 *   在编译期拦下 —— 别让它在运行期表现成「AWB 拿一份全 0 的统计去调 CCM」。
 */
#define CAM_AWB_STAT_ENABLE    1

/*
 * ── AWB 的估计器来源（T9）─────────────────────────────────────────
 *
 * 0 = 软件灰世界（改动前，统计采在 **CCM 之后**，已实机验证的那条路）
 * 1 = ISP 硬件白点筛选统计（统计采在 **CCM 之前**，官方采样点）
 *
 * ⚠️⚠️ **这两条路的建议值公式不同，而且不能互换。** 这是本文件最要紧的一条：
 *
 *   源=0：统计在 CCM **之后** ⇒ 改增益会改统计 ⇒ **闭环**
 *         sug = cur × g_mean / chan_mean        ← 必须乘 cur，否则不幂等
 *   源=1：统计在 CCM **之前** ⇒ 改增益**不影响**统计 ⇒ **开环前馈**
 *         sug = Σg / Σchan                      ← 绝不能乘 cur，乘了就单调发散
 *
 * 把源=0 的公式用在源=1 上，每一拍都会把**已经生效的增益再乘一遍**，增益一路
 * 单调跑到限位；而现场表现是「颜色缓慢地越来越偏，可所有计数器都显示一切正常
 * （下发在涨、没有任何一道防护在挡）」—— 最难归因的那一类错。
 *
 * 三重防呆，缺一不可：
 *   ① `cam_awb_step_hw()` 的**签名里根本没有 cur_r/cur_b** —— 结构上写不出
 *      乘 cur 的代码，不是靠注释提醒；
 *   ② 旧函数 `cam_awb_step()` **原样保留**给源=0 的回退路径，两条路各自一个
 *      函数，不做「加个参数复用一份实现」那种合并（那正是两个公式串味的入口）；
 *   ③ 宿主机用例把「不动点」钉死：固定统计连喂 200 拍，增益必须停住；
 *      并且**从任意初值出发收敛到同一个不动点** —— 误用旧公式时不动点会跟着
 *      初值跑，这条立刻红。
 *
 * ══ 换过去之后哪些判据变了（全部改成官方标定值）══
 *
 *   · 「色偏过大」防护**取消**。它是灰世界时代对「单色场景」的整幅级近似，
 *     而硬件白点筛选是**像素级**的、框来自官方标定，比猜的阈值可信。
 *     这一路上 SKIP_CAST 恒为 0。
 *   · 新增「白点太少」：counted < CAM_AWB_MIN_COUNTED（官方 awb.min_counted）
 *     ⇒ 统计不可信，整拍不动。**它替代了上面那条。**
 *   · 「暗场/过亮」防护**取消**。硬件的 white_patch.luminance 窗（164~533，
 *     由官方 green 范围与 rg/bg 范围推导）已经在像素级做了同一件事。
 *     这一路上 SKIP_DARK / SKIP_BRIGHT 恒为 0。
 *   · 增益上限从 3000 抬到 3445，见 CAM_AWB_GAIN_MAX_MILLI。
 *   · 阻尼与单步限幅**保留、但理由变了**：不再是环路稳定性（已经没有环了），
 *     而是对估计噪声的时域平滑。数值一个不动，免得同时改两件事。
 *
 * ⓘ 那三个恒为 0 的计数器**保留不删**：源=0 的回退路径还要用，而且「它恒为 0」
 *   本身就是一条现场信息 —— 它证明确实走的是硬件那条路。
 *
 * 回退：设 0 立刻回到已实机验证的软件灰世界（硬件统计仍然建、自检行那组并排
 * 对照仍然在），无需改别的地方。
 * ⚠️ 依赖 CAM_AWB_STAT_ENABLE = 1；不相容的组合由 camera_csi.c 的 #error 拦下。
 */
#define CAM_AWB_SOURCE         1

/*
 * 白点数的可信门限（官方 awb.min_counted）。低于它这一拍**整个不动**。
 * 1200 相对 1280×720 = 921600 是 0.13% —— 门槛很低，它挡的是「镜头怼着单色
 * 物体、几乎没有中性像素」那种场景，不是「白点少了点」。
 * ⚠️ 必须与 cam_isp_cal.h 的 CAM_CAL_MIN_COUNTED 相同，camera_csi.c 有
 *   _Static_assert 把两边钉在一起（本文件是纯逻辑，不许 include 标定表）。
 */
#define CAM_AWB_MIN_COUNTED    1200

/*
 * 白点**重心**必须落在官方轨迹的包围盒里（= awb.range，也就是白点轨迹 bp 的
 * 包围盒）。硬件已经按同一组数逐像素筛过一遍了，这里判的是**累加之后的重心**
 * —— 边界附近的像素能各自通过逐像素筛选，但重心跑出盒子说明场景不是中性的。
 * 单位与 cam_awb_ratios() 的输出一致（×10000）。
 * ⚠️ 四个数必须与 cam_isp_cal.h 的 CAM_CAL_RG/BG_* 相同，同样由 _Static_assert 守着。
 *
 * ⓘ 这个盒子与增益限幅是**自洽**的，不是两套独立的钳制：
 *     kr = 1/rg ∈ [10^7/8790, 10^7/3801] = [1138, 2631]
 *     kb = 1/bg ∈ [10^7/6587, 10^7/2903] = [1518, 3445]
 *   全部落在 [CAM_AWB_GAIN_MIN_MILLI, CAM_AWB_GAIN_MAX_MILLI] 之内
 *   ⇒ 通过盒子的建议值**永远不会被限幅改写**，两道判据不会互相打架。
 *   test_cam_tune.c 的可调参数自检把这条不变式钉住了。
 */
#define CAM_AWB_RG_MIN_Q4      3801
#define CAM_AWB_RG_MAX_Q4      8790
#define CAM_AWB_BG_MIN_Q4      2903
#define CAM_AWB_BG_MAX_Q4      6587

/*
 * oneshot 的等待上限，毫秒。
 *
 * ⚠️⚠️ **只用 oneshot，绝不调 esp_isp_awb_controller_start_continuous_statistics()。**
 * 理由是 rev v1.0 上的一处纯浪费：esp_isp_awb_isr() **无条件**读 25 个 subwindow
 * 的 LUT —— 每个子窗 4 次 `set_cmd + get`，共 **100 次寄存器往返**，并往 ISR 栈上
 * 拷 416 字节（16 B 主窗 + 400 B 子窗）。而 rev < 3.0 **根本没有 subwindow**
 * （isp_awb.c 的 efuse_hal_chip_revision() < 300 分支打个 warning 就跳过配置），
 * 那 400 字节全是垃圾。连续模式 = 每帧一次这样的 ISR；oneshot = 每秒一次。
 *
 * 60 ms = 两个传感器帧周期（30 fps ⇒ 33.3 ms）。**阻塞发生在帧泵任务里**，
 * 而帧泵走的是 vTaskDelayUntil(100 ms) 的固定节拍：只要一拍内的总耗时
 * （取帧 + 统计 + 本次阻塞 ≤35 ms + 缩放 4.2 ms + 编码 9.1 ms）< 100 ms，
 * **帧率一点都不掉**。实测值要写进 README。
 * 若实测 fps 掉到 9 以下或「拒收」非零：先把 CAM_AWB_INTERVAL_TICKS 拉到 20
 * （2 秒一次），仍不够才考虑把触发点挪到 uvc_stream.c 提交之后。
 *
 * ⚠️ **不能传 0**：驱动把 timeout_ms = 0 解读成「触发一次立刻返回、结果走回调」，
 *   而我们没注册回调 —— 它会在统计还没做完时就 isp_ll_awb_enable(false) 把统计
 *   关掉，现场表现是「触发在涨、白点恒为 0」。
 */
#define CAM_AWB_ONESHOT_MS     60

/*
 * 统计侧的软件黑电平（BLC）扣除，单位 = 8 位码值。**默认 0。**
 *
 * rev v1.0 用不了 ISP 的 BLC 块；若 T7 的黑位实测判定传感器侧也压不掉那个基座
 * （官方 acc.blc = 16），就在**统计上**把它减掉：
 *     Σx' = Σx − p × counted
 * 硬件给的 counted 就是参与累加的像素数，所以这个减法是**精确**的，不是估计。
 *
 * ⚠️ 它修正的只是**白点估计**（进而是 kr/kb 与 CCT），**修不了画面** ——
 *   画面上的基座只能靠传感器自己的 BLC（CAM_SENSOR_BLC_ENABLE）或降 CCM 强度
 *   处理。填 16 之前必须先按 CAM_SENSOR_BLC_ENABLE 那一节的测法量出基座确实 ≈16，
 *   否则等于凭空把 rg/bg 往偏离 1 的方向推。
 */
#define CAM_STAT_BLC_PEDESTAL  0

/*
 * 更新周期，单位「拍」（一拍 = UVC 帧泵一帧 = 100 ms）。10 拍 = 1 秒。
 *
 * 为什么比 AE 的 3 拍慢一大截 —— 这是**与 AE 解耦的第二条措施**（第一条是
 * 归一化，见 cam_awb_step 的说明）：两个闭环吃同一份统计量，AWB 改 CCM 会把
 * 画面整体抬亮、AE 会把它看成扰动。控制上处理这种耦合的标准手段是**时间尺度
 * 分离** —— 让慢环（AWB）的周期远大于快环（AE）的整定时间，慢环每次看到的
 * 就是快环的稳态，而不是它的暂态。AE 从最坏情况收敛约 6 步 × 300 ms ≈ 2 秒，
 * 加上 AWB 还要等 AE 报收敛才动（第三条措施），1 秒的周期已经足够。
 * 调大 = 更稳更慢；调小到 AE 周期附近 = 两个环互相追着跑，颜色与亮度一起喘。
 */
#define CAM_AWB_INTERVAL_TICKS 10

/*
 * 死区：建议增益与当前增益相差不到这个百分比就完全不动。
 * 5% 的增益差在画面上基本看不出（≈ 半个 JND），却足以让统计噪声每秒重配一次
 * CCM —— 那是 9 个寄存器的写，还会让「已收敛」这个观测量永远为假。
 */
#define CAM_AWB_DEADBAND_PCT   5

/*
 * 阻尼：每次只走到建议值的 NUM/DEN。理由与 AE 那一处同源 ——
 * 从「改 CCM」到「测到反映它的那一帧」同样有 100~200 ms 的滞后，
 * 带滞后的比例环节增益 1.0 就在振荡边缘。代价只是多花一两个周期收敛。
 */
#define CAM_AWB_DAMP_NUM       1
#define CAM_AWB_DAMP_DEN       2

/*
 * 单步限幅：一个周期内增益最多变这个百分比。
 * 25% 的意思是最坏情况下从 1.000 走到 3.000 要 5 个周期（5 秒）—— 慢，但
 * **单调、不过冲**。白平衡的过冲比曝光的过冲更难看：颜色反向偏一下，人眼对
 * 色偏的敏感度远高于对亮度的。
 */
#define CAM_AWB_STEP_MAX_PCT   25

/*
 * ══ 灰世界失效的四道防护 ══
 *
 * 灰世界假设说的是「一幅普通画面里所有颜色的平均是灰的」。它对**混杂场景**
 * 大体成立，对**单色场景**则完全不成立 —— 镜头怼着一堵红墙时，灰世界会认定
 * 红通道太强、把红压下去，结果红墙变成灰墙、画面其余部分泛青。这是闭环 AWB
 * 的头号通病，必须挡住。四道判据各挡一类，且**每一道都能在自检行里单独看到
 * 计数**，出问题时分得清是被哪一条挡的。
 *
 * ① 亮度下限：画面太暗时通道均值由**读出噪声**主导（暗处信噪比 <1），
 *   比值纯属随机。20 ≈ AE 目标 62 的三分之一 —— 低到这个程度说明 AE 已经
 *   顶到限位还不够亮，此时的颜色信息不可信。
 *   ⚠️ 这个数**必须跟着 CAM_AE_TARGET 缩放**（原来是 40 配目标 120）。忘了改的
 *      后果很隐蔽：目标降到 62 而闸留在 40 时，40 就成了目标的 65%，正常曝光的
 *      画面会被判成「暗场」⇒ AWB 一步都不走、颜色永远停在静态初值，而自检行
 *      只会显示「暗场」在涨。
 * ② 亮度上限：大面积接近削顶时通道均值被 255 **截断**，比值同样失真
 *   （原本 300 与 400 的两个通道都变成 255，看起来「已经平衡」）。
 *   200 留了 55 的余量给正常画面里的高光。
 * ③ 色偏上限：三个通道均值的 max/min 超过这个倍数就认为场景是单色的，不更新。
 *   200 = 2.00×。定这个数的依据：白平衡大体正确时，**普通混杂场景**（含人脸、
 *   木色家具、暖光）的通道均值比很少超过 1.7×，而单色场景轻易到 3× 以上 ——
 *   红墙 R200/G60/B55 ⇒ 3.6×，绿植 R55/G150/B50 ⇒ 3.0×，蓝天 R70/G110/B210
 *   ⇒ 3.0×，都被这条挡住。调小 = 更保守（更多正常场景也不更新），
 *   调大 = 开始被单色场景带偏。
 *   ⓘ 通道均值为 0 时按「无穷大色偏」处理（同时也顺手挡住了除零）。
 * ④ 增益合理范围：算出来的建议增益必须落在 [MIN, MAX] 之内，否则**这一拍
 *   整个不更新**（而不是钳到边界上采纳）—— 跑出这个范围本身就说明这份统计
 *   不可信，采纳一个钳过的值等于把错误的方向照走不误。
 *   下限 1.000 不是随便定的：Bayer 阵列 50% 是绿像素、绿滤光片透过率也最高，
 *   **绿通道恒为三者中最强**，所以 R/B 相对 G 的增益在物理上不可能小于 1。
 *   上限 3.000 覆盖到白炽灯（2700K，蓝通道很弱，B 增益约 2.5~3）；再往上
 *   就逼近硬件定点格式的 4.0 死线了，而且那种照明下噪声已经先崩。
 */
#define CAM_AWB_LUM_MIN        20
#define CAM_AWB_LUM_MAX        200
#define CAM_AWB_CAST_MAX_PCT   200
#define CAM_AWB_GAIN_MIN_MILLI 1000
/*
 * 增益上限跟着估计器走（下限 1000 两条路共用，理由见上面 ④）：
 *
 *   源=1（硬件白点）3445 = 10^7 / CAM_AWB_BG_MIN_Q4 —— 官方白点轨迹端点给出的
 *     kb 最大值（2289 K 的白炽灯）。留在 3000 的话在暖光下会顶住，表现为
 *     「白炽灯下永远偏黄」，而现场只看到增益贴着上限不动。
 *     3.445 < 4.0 ⇒ 仍在 rev < 3.0 那个 S2.10 定点格式的表达范围内。
 *   源=0（软件灰世界）3000 —— 改动前那个已实机验证的值，一个字不动。
 *     灰世界推出来的建议本来就没有官方轨迹兜底，放宽上限等于放宽它被单色场景
 *     带偏的幅度，那是**两件事**，不该顺手一起改。
 */
#if CAM_AWB_SOURCE
#define CAM_AWB_GAIN_MAX_MILLI 3445
#else
#define CAM_AWB_GAIN_MAX_MILLI 3000
#endif

/* 连续这么多个更新周期落在死区内就报「收敛」。纯观测量，不参与控制。 */
#define CAM_AWB_CONVERGE_TICKS 3

/* ══════════════════════════════════════════════════════════════════════
 *  官方前馈画质级（开环查表，**不是闭环**）
 * ══════════════════════════════════════════════════════════════════════
 *
 * 官方 IPA 把 ISP 各画质级的参数按**当前工作点**查表下发，不带任何误差反馈
 * （adn / acc / aen 三个模块的表全部以 gain / color_temp / luma 为索引，没有误差
 *  项，见 docs/superpowers/research/2026-08-19-esp32p4-official-isp-pipeline.md §B.1）。
 * 我们照此办理：标定表在 cam_isp_cal.h（机械生成），查表逻辑在 cam_isp_map.c
 * （纯逻辑、宿主机可测），本文件只放开关与迟滞。
 *
 * ⚠️ **每一组前馈级各有一个编译开关，是为了能分别 bisect。** 现场若发现画面出
 *   问题，把其中一个改成 0 重编即可确定是哪一级 —— 关掉时该级**一行代码都不进
 *   镜像**（整段 #if 掉），硬件停在寄存器复位值，也就是本组前馈级上线之前那个
 *   已实机验证过的状态。**全部关掉的构建也必须能编过**，这条每次都验。
 */

/* T2：BF（Bayer 域降噪）+ Demosaic 梯度比，按传感器总增益分档。 */
#define CAM_ADN_ENABLE   1

/* T3：LSC 镜头阴影校正（暗角）。 */
#define CAM_LSC_ENABLE   1

/* T4：SHARP 锐化（按增益）+ Color 对比度（按增益）/ 饱和度（本阶段钉住）。 */
#define CAM_AEN_ENABLE   1

/*
 * T12（**提前到这里做**）：gamma 曲线。
 *
 * ══ 为什么把它从 T12 提前 ══════════════════════════════════════════
 *
 * 实拍对比：同一间屋子，Mac 内置摄像头曝光正常，我们的图**几乎全黑、偏红棕**。
 * 根因不在曝光，在**输出的传递函数**：我们直出**线性光**，而主机把 MJPEG 一律
 * 按 sRGB（≈ γ 2.2 解码）解释。实测线性均值 45 ⇒ 主机解出来的是
 * (45/255)^2.2 = 0.020 的相对亮度，等于又被压暗 **50 倍**。
 * 开了 gamma 之后同一个线性 45 被编码成 F(45) = 107（γ=0.5 档），主机解成
 * (107/255)^2.2 = 0.15 —— 这才是一张正常曝光的图。
 * ⇒ **gamma 单独一项就能把画面从「几乎全黑」拉到大致正常**，它不是画质微调，
 *   是这条链路上缺的一个必需环节，所以不该排在队尾。
 *
 * ══ 提前的代价，以及怎么还上 ═══════════════════════════════════════
 *
 * 原计划把它排在 T12 是因为一条真实的耦合：gamma 是**逐通道的非线性幂律**，
 * 会把 1.23 的通道比压成 1.23^0.605 = 1.135（7.7%），而我们的 AE/AWB 统计采在
 * **ISP 输出**（gamma 的下游）⇒ 一开 gamma，灰世界 AWB 的反馈量就失真。
 *
 * 还法：gamma 是**已知、单调、逐通道**的曲线 ⇒ 在软件统计里用一张逆表把采样点
 * 还原回线性域再算均值（cam_frame_stats_rgb565_lut + cam_gamma_inverse_lut）。
 * 两个闭环的输入域因此完全不变，代价是 256 字节的表与每个采样点 3 次查表。
 * ⚠️ 这条还法成立的前提是**逆表与实际下发的那档曲线严格同源**。所以运行期
 *   「配硬件」与「建逆表」被绑在同一个函数里（camera_csi.c 的 camera_gamma_apply），
 *   不给它们各自走一条路的机会。
 *
 * ══ 关掉之后 ═══════════════════════════════════════════════════════
 *
 * = 0 时 gamma 一行代码都不进镜像，**逆变换也跟着旁路**（统计不传逆表 ⇒ 恒等
 * ⇒ lin_* 逐位等于原值）⇒ 完整回到本改动之前那个已实机验证过的行为。
 */
#define CAM_GAMMA_ENABLE 1

/*
 * ── gamma：按 env.luma 动态选档（T12）───────────────────────────────
 *
 * 官方 4 档 γ = 0.500 / 0.560 / 0.605 / 0.655，按 **env.luma**（环境照度量）选档，
 * 断点 15.1 / 30.1 / 90.1 / 300.1，迟滞 luma_min_step = 3.0。
 * env.luma 由 T11 的直方图重建（cam_env_luma_q1 / cam_env_luma_from_ev），
 * 选档与迟滞由 cam_gamma_slot() 做 —— 两个函数 T1 就写好并测过了。
 *
 * 1 = 动态选档（官方口径）。**这是 T12 相对 751b24bb 唯一改的画质行为**：
 *     那一版把档钉在第 0 档（γ=0.5），理由是用户那间屋子里 AE 已经顶格
 *     ⇒ 官方也会选第 0 档；亮场则会偏亮/偏平（中灰处 F0(62)=126 对 F3(62)=101，
 *     差 25 级）。接上 env 之后这个边界消失。
 * 0 = 钉在 CAM_GAMMA_SLOT 档，逐位回到 751b24bb 的行为（现场 bisect 的退路）。
 *
 * ⚠️⚠️ **换档时统计侧的逆 gamma 表必须跟着换。** 这条由 camera_gamma_apply()
 *   的结构保证（下发硬件与重建逆表绑在同一个函数里），不靠调用方记得。
 *   逆表与硬件曲线一旦不同源，AE/AWB 会拿一个系统性偏移过的反馈量安静地闭环，
 *   画面上看不出任何异常、而自检行里的每个数都仍然「自洽」——
 *   用错邻档的误差是十几级量级（宿主机用例 ⑦ 守着），与舍入余量差一个数量级。
 *
 * ⓘ 换档那一瞬间有 **1~2 帧**的过渡误差：CSI 里可能已经排着用旧曲线拍好的帧，
 *   而它会被新逆表还原。影响范围只有**软件帧统计**（自检行的「建议」，以及
 *   CAM_AE_SOURCE/CAM_AWB_SOURCE = 0 时的两个闭环）；两个源都是 1 时，硬件
 *   AE/AWB 的抽头都在 gamma **上游**，一点都不受影响。迟滞把换档压到很低频，
 *   这份过渡误差最多每几秒出现两帧，不进任何判据。
 */
#define CAM_GAMMA_ADAPTIVE  1

/*
 * ── gamma：CAM_GAMMA_ADAPTIVE = 0 时钉住的那一档 ──────────────────
 *
 * 也是**开机第一次**下发的档（那时直方图还没出过数、env.luma 还不存在）。
 *
 * 取第 0 档（γ = 0.500）的两条理由：
 *  ① 它是四档里最接近 sRGB 编码指数 1/2.2 = 0.4545 的一档，而「主机按 sRGB
 *     解码」正是 751b24bb 要治的病。取 γ=0.5 时端到端是 linear^(0.5×2.2) =
 *     linear^1.10，几乎就是恒等；取末档 0.655 则是 linear^1.44，画面仍偏暗。
 *  ② 开机头一秒宁可偏亮不要偏暗：偏亮看得见、偏暗看起来像「没出图」。
 */
#define CAM_GAMMA_SLOT   0

/*
 * 前馈重配的迟滞：档位算出来变了，也要**连续**这么多拍都指向新档才真的下发。
 *
 * 为什么必须有：rev < 3.0 **没有影子寄存器**（isp_ll_shadow_update_* 在该分支里
 * 是恒真的空桩），参数写下去立刻生效、**没有帧边界原子性** —— 帧中途换 BF 模板
 * 会出现单帧的上下半张不同处理。AE 在档位断点上抖一下就重配一次的话，那种撕裂
 * 会以「偶发横向亮带」的形式出现，而且极难归因。
 * 3 拍 = 300 ms，与 AE 的更新周期（CAM_AE_INTERVAL_TICKS = 3）同量级，
 * 代价是换档慢 0.3 秒，肉眼不可见。自检行打「重配=」计数，它若随时间线性增长
 * 就说明迟滞没起作用（或者增益真的在持续变），先看这个数再去调它。
 */
#define CAM_FEEDFWD_HYST_TICKS  3

/*
 * ── LSC：按色温选档（T13）────────────────────────────────────────
 *
 * cam_isp_cal.h 带了三档（2410 / 5210 / 8200 K）。
 * 1 = 按 CCT 取**最近邻**（不插值）。为什么不插值：273×4 个值插值要 1092 次乘加，
 *     而三档之间最大差 0.36（R 通道四角，其余三个通道差 <0.21），插值换来的
 *     精度提升在一个 ~3× 的四角提亮上看不出来。
 * 0 = 钉在 CAM_LSC_SLOT_DEFAULT，回到 T3~T12 的行为。
 *
 * ⚠️⚠️ **LSC 换档的迟滞要比别处更狠**：它是本计划里最贵的一次重配
 *   （273 × 2 条 LUT 写命令，约 0.5 ms），而 rev v1.0 没有影子寄存器 ——
 *   写到一半就是**可见的暗角跳变**。所以用 CAM_FEEDFWD_HYST_TICKS × 2
 *   （6 拍 = 600 ms），是其余前馈级的两倍。
 *
 * ⓘ 换档的「可信」由**输入端**保证而不是由时机保证：s_cct_k 只在白点数达到官方
 *   min_counted 时才更新（camera_csi.c 的 camera_awb_stat_tick）⇒ 白点不够的
 *   场景里 CCT 整个冻住，LSC/CCM/饱和度自然都不动。这比「只在 AWB 判定 APPLIED
 *   或 SKIP_BAND 的那一拍评估」更简单：可信性是那个**数**的属性，不是某一拍的属性。
 */
#define CAM_LSC_BY_CT  1

/*
 * CAM_LSC_BY_CT = 0 时钉住的档；也是**开机第一次**下发的档（那时还没有 CCT 估计）。
 * 取中间那档的依据：只有 R 通道随色温有明显差异，2410 与 8200 之间最大差 0.71，
 * 取中点后两侧残差各 ≈0.36，落在一个 ~3× 的四角提亮上 ≈ 12%，且在四角、
 * 还会被 CCM/AWB 部分吸收 ⇒ 看不出来。
 * ⓘ 它与 CAM_CCT_DEFAULT_K = 5210 指的是同一档（cam_cal_lsc_cct[1]）——
 *   「没有 CCT 时」两条路径给出同一个结果，不必分别推理。
 */
#define CAM_LSC_SLOT_DEFAULT  1

/*
 * ── LSC：表的行列是否需要转置 ────────────────────────────────────
 *
 * ⚠️ 这是一个**已知缺口的开关，不是可调参数**。
 *
 * 驱动按 `i = y × num_grids_x + x` 写 LUT（isp_lsc.c），也就是 **x 快变**；
 * 而官方 JSON 里那 273 个数到底是 x 快变还是 y 快变**没有任何文档说明**，
 * 提取脚本按 x 快变原样搬运。两者若不一致，21×13 的表会被当成 13×21 读，
 * 现象是**暗角修正方向横竖颠倒**：画面上下变亮、左右反而更暗。
 *
 * 上板看到那个现象就把这里改成 1 重编（下发时按 (x,y) → (y,x) 重排），
 * **不要**去改提取脚本或标定表 —— 表是机械生成的，改了 `--check` 就会失败。
 * 默认 0 = 不转置（照搬 JSON 的原始顺序）。
 *
 * ⓘ 转置只在 21×13 与 13×21 之间搬运，两者格数相同（273），所以转置版本不会
 *   越界；但它把 21 列的表按 13 列解释，几何上是错的 —— 只有实测能定谁对。
 */
#define CAM_LSC_TRANSPOSE     0

/*
 * ══════════════════════════════════════════════════════════════════════
 *  T7：黑电平（黑位基座）—— ⛔ T10（官方 CCM）的判定点
 * ══════════════════════════════════════════════════════════════════════
 *
 * ══ 问题 ══
 *
 * 本板 rev v1.0 的 **ISP BLC 直接返回 ESP_ERR_NOT_SUPPORTED**（isp_blc.c:30 的
 * ESP_CHIP_REV_ABOVE(rev,300)），而官方 SC202CS 标定文件里的 acc.blc 说这颗
 * 传感器有 **16/255 的黑电平基座**。
 *
 * 基座本身只是让黑位发灰，真正的问题在 T10：白平衡增益要乘进 CCM，一个**等值**
 * 基座 p 会被 W = diag(kr,1,kb) 变成**不等值**基座 (kr·p, p, kb·p)，再被官方 CCM
 * 的大负非对角项放大 —— 5040 K + kr1.8/kb1.85 + p=16 时约 (+23, −8, +21)，
 * 也就是**可见的品红色黑位**。在一个未知的基座上做 19 档大动态矩阵运算，
 * 画面变化无法归因，投入产出不成立。
 *
 * ══ 所以先量 ══
 *
 * 量具是 cam_frame_stats 的 lin_*_min 四个数（**线性域**，见 cam_frame_stats.h
 * 里为什么必须是线性域），自检行「黑位」那一行打出来。
 *
 * **测法（不照做数字就没有意义）**：
 *   ① 用不透光的东西**完全盖住**镜头（镜头盖 / 黑胶带 / 手掌紧贴，环境要暗）；
 *   ② 等 10 秒让 AE 顶到上限（自检行 AE 那格应当是 曝光=1244/1244、增益顶格）；
 *   ③ 读「线性最暗 r/g/b」，取三次的最小值（长曝光高增益的读出噪声会让它偏高）。
 *
 * ══ 唯一的执行点：传感器自带的 BLC ══
 *
 * esp_cam_sensor 的 SC202CS 寄存器表最后有一行被**注释掉**的：
 *     // {0x3902, 0x80}, // blc disable. 0xc0 enable
 * （sc202cs_mipi_1lane_24Minput_1280x720_raw8_30fps.h 倒数第 3 行）
 * ⇒ 这颗传感器**自己有 BLC**，只是既没显式开也没显式关，停在上电默认值。
 * 官方在 esp_video 里对 rev<3.0 的处置是「没有任何软件替代，黑电平只能靠传感器
 * 自己处理」—— 这一行就是把那句话落到实处的**唯一**位置。
 *
 * ⚠️ **默认关（0），这是有意的。**
 *   ① 那行注释来自厂商寄存器表，**不是数据手册**；0x3902 的位定义我们并不掌握。
 *   ② 本工程反复验证有效的纪律是「先量、再切」（T5 整个任务就是为这条纪律而存在）。
 *      开着烧第一版的话，「基座本来是多少」这个数就永远拿不到了 —— 而它正是
 *      T10 判定表的输入。
 *   ③ 顺序天然就是对的：**第一次烧 = Step 1 的「写之前」**，把开关翻成 1 再烧
 *      = Step 3 的「写之后」，两次自检行一比就是 T7 要的那个前后差异。
 *
 * ══ 判读与下一步 ══
 *
 * | 关着测到的 lin r/g/b | 结论 | 动作 |
 * |---|---|---|
 * | 都 <= 3        | 传感器自己的 BLC 已经在工作，基座 ≈ 0 | 开关保持 0，**什么都不做**；T10 放行 |
 * | 10~20 且相近   | 基座 ≈ 16，与官方 acc.blc 精确吻合 | 开关翻成 1 重烧，再测一次 |
 * | 彼此差 > 5     | 基座自带色偏，或被 LSC/CCM 放大 | 先把 CAM_LSC_ENABLE 临时改 0 重测，隔离出真实基座 |
 * | > 30           | 不是黑电平，是漏光/没盖严 | 重新盖，别急着写寄存器 |
 *
 * 开成 1 之后**必须再测一次**，判据：`线性最暗 r/g/b` 全部降到 <= 3。
 * 任何异常（画面出现横条纹 / 暗部溢出成纯黑 / PID 读不到 / 取不到帧）一律改回 0。
 *
 * ⓘ 自检行会同时打出 0x3902 **写之前的读回值** —— 这一条零风险、开关关着也做，
 *   它单独就能回答「传感器的 BLC 上电默认是开还是关」：读回 0xc0 ⇒ 本来就开着
 *   ⇒ 基座该是 0，上面那张表里第一行；读回 0x80 ⇒ 关着 ⇒ 预期基座 16。
 */
#define CAM_SENSOR_BLC_ENABLE  1
#define CAM_SENSOR_BLC_REG     0x3902
#define CAM_SENSOR_BLC_VAL     0xc0

/*
 * ══════════════════════════════════════════════════════════════════════
 *  T11：直方图统计 —— 场景均值 / 亮暗块占比 / env.luma 的索引量
 * ══════════════════════════════════════════════════════════════════════
 *
 * 官方把「测光」与「环境照度」分成**两张权重表**（agc.luma_adjust.weight 是
 * 中心加权金字塔，ian.luma.env.weight 是全 1），正是为了让 gamma 选档不跟着
 * AE 的测光抖 —— 一盏台灯照亮画面中心时 AE 该收敛，但环境并没有变亮。
 * 我们照此办理：AE 继续吃 5×5 中心加权，本统计块用**近似均匀**的权重给出
 *   ① 场景均值（env.luma 的输入）
 *   ② 亮块 / 暗块占比（T12 背光判据的输入）
 *
 * ⚠️ 关掉（= 0）时整块统计一行代码都不进镜像，帧泵里也没有那次 oneshot 阻塞，
 *   行为与 T11 之前逐位一致 —— 现场 bisect 的退路。CAM_GAMMA_ADAPTIVE 与
 *   CAM_BACKLIGHT_ENABLE 都依赖它，不相容的组合由 camera_csi.c 的 #error 拦下。
 */
#define CAM_HIST_ENABLE  1

/*
 * 直方图 oneshot 的触发节奏。**必须与 AWB 的 oneshot 错开半个周期。**
 *
 * 两者都会在帧泵任务里最多阻塞 CAM_*_ONESHOT_MS 毫秒；撞在同一拍就是
 * 120 ms > 帧泵 100 ms 的固定节拍 ⇒ 「拒收」立刻非零、帧率掉下来。
 * AWB 的相位是 CAM_AWB_INTERVAL_TICKS（第 10、20、30… 拍），这里取 5
 * ⇒ 第 5、15、25… 拍，两者永不同拍。
 *
 * ⚠️ 改 CAM_AWB_INTERVAL_TICKS 时这两个数要一起看：CAM_HIST_PHASE 必须是
 *   一个**不会与 AWB 相位重合**的余数（最稳的取法就是周期的一半）。
 */
#define CAM_HIST_INTERVAL_TICKS  10
#define CAM_HIST_PHASE           5

/*
 * oneshot 的等待上限，毫秒。取值理由与 CAM_AWB_ONESHOT_MS 完全相同
 * （60 ms = 两个传感器帧周期；不能传 0，那会被驱动解读成「触发后立刻返回、
 *  结果走回调」，而我们没注册回调）。
 */
#define CAM_HIST_ONESHOT_MS      60

/*
 * ── env.luma 的重建模型 ──────────────────────────────────────────────
 *
 * 1 = 官方 k/ev 重建：env_q1 = CAM_CAL_ENV_K × 10 × 场景均值 / (AE目标 × ev)。
 *     这条式子标 **[反推，数值一致性]**，不是 [确证]：把官方四个 gamma 断点
 *     15.1/30.1/90.1/300.1 代进去得 ev = 16556/8306/2775/833，全部落在我们
 *     ev ∈ [8, 19904] 的值域内且分布合理 —— 像但不等于确证。
 * 0 = 降级路径：直接按**实测的四个 ev 值**插值（cam_env_luma_from_ev），
 *     gamma 的四条曲线与四个断点仍是官方的，只换掉 ev→env 这一段换算。
 *
 * ══ 什么时候翻成 0 ══（判据必须先写好，别临场发挥）
 *
 * T11 的成功判据之一：从明亮日光走到昏暗室内，自检行的 `env.luma` 应当**跨过
 * 至少两个官方断点**（即「用过的档」至少出现两个不同的数）。若四档只用得到
 * 一档，或 env 恒在 3001 以上 / 151 以下 ⇒ **这条重建就是错的**，翻成 0，
 * 并把下面四个 ev 断点换成实测值（写清楚哪种光照、AE 收敛后的 ev 是多少）。
 *
 * 默认值就是官方 k 反推出来的那四个数 ⇒ CAM_ENV_MODEL = 0 与 = 1 在 AE 收敛
 * （场景均值 ≈ 目标）时给出**同一条曲线**，翻开关本身不改变行为，只把「按什么
 * 索引」这件事从公式换成查表。真正的改变发生在你把这四个数换成实测值那一刻。
 */
#define CAM_ENV_MODEL      1
#define CAM_ENV_EV_BREAKS  { 16556, 8306, 2775, 833 }

/*
 * ── Color：饱和度按色温选（T13）──────────────────────────────────
 *
 * 官方 acc.saturation 只有两档：{0 → 128, 4500 → 130}，即 >= 4500 K 用 1.016×。
 * 1 = 按 CCT 选（官方口径）；0 = 钉在 CAM_SATURATION_FIXED_VAL。
 *
 * ══ 对 AWB 的影响：**理论上恰好为零**（T4 那条 0.34% 的估算已经过时）══
 *
 * T4 算过 130（1.0156×）对 AWB 建议增益的扰动 ≈ 0.34%，但那是在**软件灰世界**
 * 下算的 —— 当时统计采在 ISP 输出，而 Color 块就在它上游。
 * T9 之后 AWB 已经切到**硬件白点统计**，采样点是 ISP_AWB_SAMPLE_POINT_BEFORE_CCM，
 * 而 Color（对比度/饱和度）在 YUV 域、位于 CCM 的**下游** ⇒ 饱和度对硬件 AWB 的
 * 读数**不是「影响很小」而是「不在同一条路径上」**。硬件 AE 同理
 * （ISP_AE_SAMPLE_POINT_AFTER_DEMOSAIC，同样在 Color 上游）。
 *
 * ⚠️ **但那 0.34% 并没有消失，它挪到了两个回退档上**：
 *   CAM_AWB_SOURCE = 0（软件灰世界）或 CAM_AE_SOURCE = 0（软件线性均值）时，
 *   统计仍然采在 ISP 输出 = Color 的下游 ⇒ 那 0.34%（AWB）与 ~3%/−0.4%（AE，
 *   对比度那一侧）原样回来。两者都远小于各自的死区（AWB 5%、AE 8/62 ≈ 13%），
 *   所以回退档也仍然成立 —— 但判读那两个档的自检行时要知道这一份偏差存在。
 * ⓘ 自检行的「建议 R×/B×」永远走软件统计 ⇒ 它**一直**带着这 0.34%。
 *   拿它抄回 CAM_CCM_GAIN_R/B_MILLI 做静态标定时，这个量级可以忽略。
 */
#define CAM_SAT_BY_CT  1

/* CAM_SAT_BY_CT = 0 时钉住的值；也是开机第一次下发的值（128 = 1.000×，
 * 与「不配 color 块」在饱和度上完全等价 ⇒ 开机头一秒不引入任何色度改动）。 */
#define CAM_SATURATION_FIXED_VAL  128

/*
 * 饱和度按色温选档时，4500 K 这个门限两侧的迟滞，单位 K。
 * CCT 恰好落在 4500 附近时（黄昏、暖白 LED）估计噪声会让它在 128/130 之间抖，
 * 而每次抖都是一次 Color 块重配。150 K ≈ CCT 估计在中段的分辨率（相邻标定点
 * 之间 300~500 K），取半个格。
 * ⓘ 128 与 130 只差 1.6%，抖起来肉眼看不出 —— 这道迟滞防的是**无谓的重配**，
 *   不是可见的画面跳变。
 */
#define CAM_SAT_CT_HYST_K  150

/* ══════════════════════════════════════════════════════════════════════
 *  自动曝光：数据结构与控制律
 * ══════════════════════════════════════════════════════════════════════ */

/*
 * 传感器给出的可调范围。全部**运行时向 esp_cam_sensor 查**（query_para_desc），
 * 不写死：曝光上限跟着 VTS 走，增益表长度跟着 menuconfig 的
 * CONFIG_CAMERA_SC202CS_ABSOLUTE_GAIN_LIMIT 与增益优先策略走，抄成常量必然过期。
 */
typedef struct {
    uint32_t exp_min;          /* 曝光寄存器值下限 */
    uint32_t exp_max;          /* 上限 */
    const uint32_t *gain_map;  /* 绝对增益表（单调升，单位 1/1000），传感器组件持有 */
    uint32_t gain_count;       /* 表长；**合法下标只到 gain_count − 1**，见下面 ⚠️ */
} cam_ae_limits_t;

/*
 * AE 状态机。曝光与增益两个旋钮被合成一个标量 **ev（曝光量）**：
 *     ev = 曝光寄存器值 × 绝对增益 ÷ 1000
 * 亮度与 ev 成正比（在不削顶的范围内），所以控制律只需要对这一个数做比例控制，
 * 「先用曝光时间、不够再加增益」的分配策略被隔离在 cam_ae_split() 里 ——
 * 控制与分配分开，两件事各自可测。
 */
typedef struct {
    uint32_t ev;          /* 当前曝光量（**量化后的实际值**，不是请求值，见 cam_ae_step） */
    uint32_t exposure;    /* 已下发的曝光寄存器值 */
    uint32_t gain_index;  /* 已下发的增益档位下标 */
    uint32_t settle;      /* 还要跳过几拍才允许再动（更新频率限制） */
    uint32_t in_band;     /* 连续落在死区内的次数，到 CAM_AE_CONVERGE_TICKS 封顶 */
    uint32_t updates;     /* 累计真正下发过多少次，自检行用 */
    uint8_t  last_mean;   /* 最近一次看到的亮度均值，自检行用 */
} cam_ae_state_t;

/* 曝光量 = 曝光寄存器值 × 绝对增益(1/1000)。溢出安全：1244 × 63008 仍在 uint32 内。 */
uint32_t cam_ae_ev(uint32_t exposure, uint32_t gain_milli);

/*
 * 把一个曝光量拆成 (曝光寄存器值, 增益档位)。
 *
 * 策略：**曝光时间优先，增益垫底** —— 曝光时间不增加噪声，模拟/数字增益都增加。
 * 只有当曝光顶到 exp_max 还不够亮时才开始往上翻增益档。
 * 增益档取「不超过所需值的最大一档」（表单调升），并同时受 CAM_AE_GAIN_MAX_MILLI 约束。
 *
 * ⚠️ 下标严格落在 [0, gain_count − 1]。**不能指望传感器驱动兜底**：
 *    sc202cs.c:1167 的 `MIN(u32_val, s_limited_abs_gain_index)` 是个 off-by-one ——
 *    当增益表里没有任何一项超过 CONFIG_CAMERA_SC202CS_ABSOLUTE_GAIN_LIMIT 时
 *    （默认恰好如此：表的最大值 63008 == 上限 63008，:1526-1532 那个循环从不 break），
 *    s_limited_abs_gain_index 停在 ARRAY_SIZE 上，于是下标 == 表长也被放行，
 *    sc202cs_gain_map[表长] 是一次**越界读**。传进去的数必须自己保证合法。
 *
 * ev 为 0 或 limits 非法时输出下限档，不会除零。
 */
void cam_ae_split(uint32_t ev, const cam_ae_limits_t *lim,
                  uint32_t *exposure, uint32_t *gain_index);

/* 用传感器的默认曝光/增益初始化状态机（它们此刻就是芯片里的实际值）。 */
void cam_ae_init(cam_ae_state_t *st, const cam_ae_limits_t *lim,
                 uint32_t exposure, uint32_t gain_index);

/*
 * 走一拍。**每帧都要调**（频率限制在函数内部做，不由调用方判断）。
 *
 * 返回 true 表示 st->exposure / st->gain_index 变了、需要下发给传感器；
 * 返回 false 表示这一拍不动（没到更新周期 / 落在死区 / 已经顶到上下限 /
 * 量化后落回同一档）—— 调用方**不要**在 false 时下发，那等于把 I2C 事务
 * 白白撒在总线上（这条总线还挂着 20 ms 轮询的触摸）。
 *
 * 四道防振荡闸的位置见上面各常量的注释。除此之外还有一条：state 里存的 ev 是
 * **量化后的实际曝光量**而不是请求值，否则每次请求与实际的那点差额会在下一拍
 * 被当成新的误差再放大一次，形成慢速极限环。
 */
bool cam_ae_step(cam_ae_state_t *st, uint8_t lum_mean, int target, const cam_ae_limits_t *lim);

/*
 * ── 目标亮度由调用方传入（T12）────────────────────────────────────
 *
 * 为什么不再直接读 CAM_AE_TARGET：官方的目标是**随场景变的**（高光优先 −3 /
 * 暗部优先 +1），而「现在是不是背光」这件事只有调用方知道（它要直方图）。
 * 把目标做成参数，控制律本身就不必知道背光是什么 —— 两件事各自可测。
 *
 * 死区**跟着目标平移**，低边 target + (LOW − TARGET) = target − 6、
 * 高边 target + (HIGH − TARGET) = target + 2 —— 官方那个非对称是死区的性质，
 * 不是 62 这个数的性质，所以平移而不是重新对称化。
 *
 * 下面两个纯函数把「判定」与「换算」从 camera_csi.c 里挖出来，宿主机可测：
 *   cam_ae_backlight()  直方图的两个标量 → 是不是背光
 *   cam_ae_target()     是不是背光 → 目标亮度
 */

/*
 * 背光判定：亮块占比 >= CAM_BACKLIGHT_BRIGHT_PCT **且** 场景均值 < CAM_AE_TARGET_LOW。
 * 判据的含义与两个门限的来历见 CAM_BACKLIGHT_ENABLE。
 * CAM_BACKLIGHT_ENABLE = 0 时恒返回 false（⇒ 恒取高光优先，官方默认模式）。
 */
bool cam_ae_backlight(uint8_t bright_pct, uint8_t scene_mean);

/* 目标亮度 = CAM_AE_TARGET + （背光 ? CAM_AE_LL_OFFSET : CAM_AE_HL_OFFSET）。 */
int cam_ae_target(bool backlight);

/* 是否已收敛（连续 CAM_AE_CONVERGE_TICKS 次落在死区内）。 */
bool cam_ae_converged(const cam_ae_state_t *st);

/* ══════════════════════════════════════════════════════════════════════
 *  白平衡：从实测通道均值反推 CCM 系数
 * ══════════════════════════════════════════════════════════════════════ */

/*
 * 由「当前生效的 CCM 增益」+「当前画面的分通道均值」算出**绝对**的建议增益。
 *
 *     建议 = 当前 × g_mean / 该通道均值
 *
 * 之所以要乘上当前值：均值是**施加 CCM 之后**测到的，直接拿 g/r 当增益就把
 * 已经生效的那一份又算了一遍，越调越偏。乘进去之后这个式子是**幂等**的 ——
 * 系数正确时三个均值相等，建议值恰好等于当前值，不会来回摆。
 *
 * 只在镜头对着白/灰面时有意义（灰世界假设）。红通道均值为 0（全黑/纯蓝画面）时
 * 该通道保持当前值不变，不会除零、也不会给出一个荒唐的建议。
 * 输出限幅到 [250, 4000]：上限是硬件定点格式的 4.0，下限防止一次误测把系数打到 0。
 */
void cam_awb_suggest(uint8_t r_mean, uint8_t g_mean, uint8_t b_mean,
                     uint32_t cur_r_milli, uint32_t cur_b_milli,
                     uint32_t *sug_r_milli, uint32_t *sug_b_milli);

/* ══════════════════════════════════════════════════════════════════════
 *  白平衡：闭环 AWB 的状态机与控制律
 * ══════════════════════════════════════════════════════════════════════ */

/*
 * 一拍的结论。**「没更新」必须能分出是被哪一条挡的** —— 否则现场只能看到
 * 「颜色不动」，说不清是场景被判成单色、还是太暗、还是已经收敛了。
 * 顺序 = 判据在 cam_awb_step() 里的先后，自检行按这个顺序打计数。
 */
typedef enum {
    CAM_AWB_APPLIED = 0,   /* 增益变了，调用方必须把新的 CCM 写进 ISP */
    CAM_AWB_SKIP_AE,       /* AE 还没收敛：亮度在变，颜色统计不作数 */
    CAM_AWB_SKIP_COUNT,    /* 白点太少（counted < 官方 min_counted）：统计不可信。
                            * **只有硬件白点那条路会出现**；软件灰世界路上恒为 0。 */
    CAM_AWB_SKIP_DARK,     /* 防护①：画面太暗，噪声主导 */
    CAM_AWB_SKIP_BRIGHT,   /* 防护②：画面太亮，通道被削顶截断 */
    CAM_AWB_SKIP_CAST,     /* 防护③：色偏过大，八成是单色场景 */
    CAM_AWB_SKIP_PERIOD,   /* 场景可信，但还没到更新周期 */
    CAM_AWB_SKIP_BAND,     /* 落在死区内：已经平衡，不用动 */
    CAM_AWB_SKIP_RANGE,    /* 防护④：建议增益跑出合理范围，统计不可信 */
    CAM_AWB_SKIP_QUANT,    /* 阻尼/限幅后整数运算落回原值，没有实际变化 */
    CAM_AWB_REASON_COUNT,
} cam_awb_reason_t;

/*
 * AWB 状态机。两个旋钮就是 CCM 对角线上的 R 与 B（G 恒为 1.000 作基准）。
 * reasons[] 是纯观测量：每一拍的结论各计一次，自检行直接打出来 ——
 * 「AWB 没在动」有八种原因，靠这个直方图一眼分清。
 */
typedef struct {
    uint32_t gain_r_milli;                  /* 当前 R 增益（= 已写进 CCM 的值） */
    uint32_t gain_b_milli;                  /* 当前 B 增益 */
    uint32_t settle;                        /* 还要跳过几拍才允许再动 */
    uint32_t in_band;                       /* 连续落在死区内的周期数，到上限封顶 */
    uint32_t updates;                       /* 累计真正改过多少次增益 */
    uint32_t reasons[CAM_AWB_REASON_COUNT]; /* 每种结论各出现过多少次 */
    cam_awb_reason_t last;                  /* 最近一拍的结论 */
    uint8_t  last_r, last_g, last_b;        /* 最近一拍看到的通道均值 */
} cam_awb_state_t;

/* 初始化到静态标定值（CAM_CCM_GAIN_R/B_MILLI）—— 开机头几拍的颜色由它决定。 */
void cam_awb_init(cam_awb_state_t *st);

/*
 * 走一拍。**每帧都要调**（频率限制在函数内部做，不由调用方判断）。
 * 返回 CAM_AWB_APPLIED 表示 st->gain_r/b_milli 变了、必须重配 CCM；
 * 其余返回值都表示这一拍不动，值本身说明为什么。
 *
 * ══ 为什么反馈量是**归一化**的通道比值 ══════════════════════════════
 *
 * 控制律的核心是 cam_awb_suggest()：建议增益 = 当前增益 × g_mean / 该通道均值。
 * 这个式子里只有**比值**，没有绝对亮度 —— AE 把曝光量翻一倍，三个通道均值
 * 一起翻倍，比值不变，建议值也不变。
 * ⇒ **AWB 对 AE 的动作天然免疫**，这是两个环解耦的第一条措施（另外两条是
 *   周期分离与下面的 ae_converged 闸）。反过来「AWB 改 CCM 会让画面变亮、
 *   扰动 AE」这个方向没法靠数学消掉，只能靠时间尺度分离 —— 好在这个方向是
 *   良性的：AE 会把多出来的亮度调回去，而调回去又不影响 AWB 的比值。
 *
 * ae_converged：AE 是否已收敛。传 false 时这一拍直接跳过（CAM_AWB_SKIP_AE）。
 *   ⚠️ 这不是「AWB 依赖 AE」，而是**只在亮度稳定的窗口里采信颜色统计**：
 *      曝光正在大幅调整时画面要么欠曝（噪声大）要么过曝（削顶），两种都会把
 *      通道比值带偏。AE 关着（查不到可调范围）时曝光是恒定的，调用方应当
 *      直接传 true —— 恒定曝光本身就是「亮度稳定」。
 */
cam_awb_reason_t cam_awb_step(cam_awb_state_t *st, uint8_t lum_mean,
                              uint8_t r_mean, uint8_t g_mean, uint8_t b_mean,
                              bool ae_converged);

/* 是否已收敛（连续 CAM_AWB_CONVERGE_TICKS 个周期落在死区内）。 */
bool cam_awb_converged(const cam_awb_state_t *st);

/* 结论的中文说法，给自检行用。任何输入都返回非空字符串。 */
const char *cam_awb_reason_str(cam_awb_reason_t r);

/* ══════════════════════════════════════════════════════════════════════
 *  白平衡：硬件白点统计（采样点 = CCM 之前）
 * ══════════════════════════════════════════════════════════════════════ */

/*
 * 硬件 AWB 主窗的一次采样。四个数直接来自 isp_awb_stat_result_t，
 * counted 是**参与累加的像素数**（硬件数出来的，不是估计）——
 * 正因为它是精确的，统计侧的黑电平扣除才能写成 Σx − p×counted 这种精确形式。
 */
typedef struct {
    uint32_t counted;              /* 落在白点框内的像素数 */
    uint32_t sum_r, sum_g, sum_b;  /* 这些像素三个通道各自的累加和 */
} cam_awb_hw_stat_t;

/*
 * 由一次硬件采样算出白点重心的色度坐标：rg = Σr/Σg、bg = Σb/Σg，**均 ×10000**
 * （与 cam_isp_cal.h 的 CAM_CAL_RG/BG_* 同一定点，可直接比大小）。
 *
 * 顺带做掉 CAM_STAT_BLC_PEDESTAL 的扣除 —— 放在这里而不是调用处，是为了让
 * 「自检行打的 rg/bg」与「控制律用的 rg/bg」**永远是同一个数**：两处各算一遍
 * 的话，某天只改了一处，现场看到的日志会与实际生效的估计悄悄脱节。
 *
 * ⚠️ 全程 uint64：Σ 的满量程 = 1280×720×255 = 2.35e8，再乘 10000 会溢出 uint32。
 *
 * 返回 false 表示这份采样**不能用**（空指针 / counted = 0 / 扣完基座后 Σg = 0），
 * 此时不写 *rg_q4、*bg_q4。返回 false 只说「算不出来」，不说「白点够不够」——
 * counted 的门限（CAM_CAL_MIN_COUNTED）是控制律的判据，不在这里做。
 */
bool cam_awb_ratios(const cam_awb_hw_stat_t *s, uint32_t *rg_q4, uint32_t *bg_q4);

/*
 * 走一拍（**硬件白点统计版**）。返回 CAM_AWB_APPLIED 表示 st->gain_r/b_milli
 * 变了、必须重配 CCM；其余返回值都表示这一拍不动，值本身说明为什么。
 *
 * ══ 与 cam_awb_step() 的两条根本差异 ══════════════════════════════════
 *
 * ① **建议值是绝对的，不是增量的。**
 *        sug_r = Σg / Σr   （单位 1/1000，即 10^7 / rg_q4）
 *    统计采在 CCM **之前** ⇒ 读数里不含已经生效的增益 ⇒ 这个式子直接给出
 *    「R 通道总共该乘多少」。**签名里没有 cur_r/cur_b 就是防呆本身** ——
 *    想乘也没得乘。完整说明见 CAM_AWB_SOURCE。
 *
 * ② **不做频率限制**（不碰 st->settle）。旧函数是「每帧都调、自己分频」，
 *    本函数是「**每拿到一份新的硬件采样调一次**」—— 周期由 oneshot 的触发
 *    节奏决定（camera_csi.c 的 camera_awb_stat_tick，CAM_AWB_INTERVAL_TICKS 拍
 *    一次）。两处都分频的话实际周期会变成 INTERVAL² 拍（10 秒一次），
 *    而现场只会看到「AWB 反应特别迟钝」。
 *    ⓘ 副作用：reasons[] 直方图在这条路上是**按秒**累加的，而软件路上是按帧。
 *      两条路的计数量级本来就不该直接对比，自检行里挨着打是为了看**分布**。
 *
 * 判据顺序 = 自检行直方图的顺序：AE 未稳 → 白点太少 → 重心越界 → 死区 → 量化。
 * ae_converged 的语义与旧函数完全一致（只在亮度稳定的窗口里采信颜色统计）。
 */
cam_awb_reason_t cam_awb_step_hw(cam_awb_state_t *st, const cam_awb_hw_stat_t *s,
                                 bool ae_converged);
