#pragma once
/*
 * 一帧 RGB565 的内容统计。**纯逻辑，不依赖 ESP-IDF**，宿主机可编译可测试
 * （test/test_cam_frame_stats.c）。
 *
 * 为什么值得单独抽出来：P4 Task8 没有任何 host 侧出口（不接 UVC），
 * 「摄像头到底取到画面没有」全靠日志里的这几个数字。而**「有帧」与「帧里有东西」
 * 是两件事** —— 一块从没被 DMA 写过的零缓冲，在帧计数上与真实画面长得一模一样。
 * 判据落在这个函数身上，所以它必须能在宿主机上被逐条验证，而不是只能上板试。
 *
 * 四个量各自回答一个问题：
 *   lum_mean            画面亮不亮（挡住镜头会掉、手电照会冲高 ⇒ 证明像素跟着物理世界变）
 *   lum_min / lum_max   画面平不平（min == max ⇒ **纯色**，即「全黑」或「全白」，
 *                       不是真实画面；真实画面必然有明暗差）
 *   checksum            画面动不动（帧与帧之间不变 ⇒ 取到的是同一块没被重写的缓冲）
 *   r/g/b_mean          画面偏不偏色（**判白平衡对不对唯一的客观手段**）
 *
 * ⚠️ 分通道均值为什么必须有：肉眼说「发绿」无法量化，也分不清两种完全不同的病因 ——
 *    白平衡缺失（三个均值成 R<G>B 的固定比例，比例与画面内容无关）与 bayer order
 *    配错（红蓝对调 ⇒ 拍红色物体时 b_mean 反而高，且伴随棋盘格高频伪影）。
 *    有了这三个数，「发绿」就从一句观感变成 R60/G120/B70 这样一组能直接算出
 *    校正系数的比例。用法见 cam_tune.h 的 cam_awb_suggest()。
 */
#include <stdint.h>

typedef struct {
    uint32_t samples;   /* 实际采样了多少个像素；0 表示参数非法，其余字段无意义 */
    uint8_t  lum_mean;  /* 采样像素的平均亮度，0..255 */
    uint8_t  lum_min;   /* 最暗的采样像素 */
    uint8_t  lum_max;   /* 最亮的采样像素 */
    uint32_t checksum;  /* 采样像素原始值的 FNV-1a 32 位散列 */
    uint8_t  r_mean;    /* 采样像素的红通道均值，0..255 */
    uint8_t  g_mean;    /* 绿 */
    uint8_t  b_mean;    /* 蓝 */
    /*
     * ── 线性域的那一份（逆 gamma 还原之后再求均值）──────────────────
     *
     * 上面四个是**采样到什么就是什么**：ISP 的 gamma 开着时它们是 gamma 编码值。
     * 下面四个是把每个采样像素先过逆表还原到线性域、**再**求的均值。
     *
     * ⚠️ 顺序不能反：gamma 是非线性的，mean(F⁻¹(p)) ≠ F⁻¹(mean(p))。
     *   一定要逐像素还原再平均，这也正是逆变换必须进到扫描循环里、
     *   而不能事后对一个均值做一次查表的原因。
     * ⚠️ 亮度用**线性化之后的三个通道**按 BT.601 重新加权，不是把 gamma 域的亮度
     *   过一次逆表 —— 亮度是三通道的线性组合，而 gamma 是逐通道的非线性，
     *   两者不可交换。
     *
     * 没传逆表（inv_lut == NULL，也就是 gamma 关着）时这四个数**逐位等于**上面
     * 那四个 —— 于是「统计在哪个域算的」这件事在两种构建下都能自洽，自检行把两组
     * 数并排打出来时，gamma 关着就是两两相等，开着就是下面那组小、上面那组大。
     */
    uint8_t  lin_lum_mean;  /* 线性域亮度均值 */
    uint8_t  lin_r_mean;    /* 线性域红通道均值 */
    uint8_t  lin_g_mean;    /* 绿 */
    uint8_t  lin_b_mean;    /* 蓝 */
} cam_frame_stats_t;

/*
 * 统计 fb 指向的 w×h 个 RGB565 像素（行内紧凑排列，无 padding）。
 *
 * step：采样步长（像素）。每 step 行取一行，行内每 step 个取一个 ⇒ 采样率 1/step²。
 *       全采样 1280×720 = 92 万像素每帧要好几毫秒，取帧循环本身就会变成被观测的
 *       干扰源（把帧率压下去，再让人以为是带宽不够）。step = 8 时只采 1/64。
 *
 * 亮度用 ITU-R BT.601 的整数近似 (77R + 150G + 29B) >> 8，三个权重加起来正好 256，
 * 所以纯白必然给出 255、纯黑必然给出 0 —— 两个端点是精确的，判读时不用留余量。
 * 5/6 位分量按「高位复制到低位」扩到 8 位（31 → 255、63 → 255），不是简单左移，
 * 否则纯白只能算到 250，「全白」这个判据就会带一个说不清的偏差。
 * **三个通道均值走的是同一套扩展**，所以 r/g/b 三个数彼此可直接比大小 ——
 * 若绿用 6 位原值而红蓝用 5 位原值，「绿比红大一倍」就成了量化位数的假象。
 *
 * 参数非法（fb == NULL / w、h、step <= 0）时把 *out 整体清零并直接返回，
 * 由 samples == 0 表达「什么都没统计到」—— 与「统计到了，结果全是 0（纯黑）」
 * 严格区分开，不共用哨兵。
 */
void cam_frame_stats_rgb565(const uint16_t *fb, int w, int h, int step,
                            cam_frame_stats_t *out);

/*
 * 同上，外加一张 256 项的**逆 gamma 查表**用来填 lin_* 那四个字段。
 *
 * inv_lut[g] = 「画面里出现 gamma 值 g 时，它对应的线性值是多少」。表由
 * cam_gamma_inverse_lut() 按**当前实际下发给 ISP 的那一档曲线**生成 ——
 * 传一张与硬件不符的表比不传更糟：AE/AWB 会拿一个系统性偏移过的反馈量去闭环，
 * 而画面上看不出任何异常。传 NULL = 恒等 = 画面本来就是线性的。
 *
 * ⓘ 逆表只作用在**采样点**上（1/step² ≈ 1.4 万个像素），不碰输出帧的任何一个
 *   字节 —— 送给主机的仍然是 ISP 直出的 gamma 图。代价是每个采样点 3 次查表。
 *
 * cam_frame_stats_rgb565() 就是本函数传 NULL 的薄封装，两者共用同一次扫描逻辑。
 */
void cam_frame_stats_rgb565_lut(const uint16_t *fb, int w, int h, int step,
                                const uint8_t *inv_lut, cam_frame_stats_t *out);
